using System.Text;

namespace SWLOR.Architecture.Tests.Debt;

/// <summary>
/// The generated debt report (<c>Baseline/Phase5/DebtReport.md</c>): the totals of every measure and its largest
/// entries. It is written with the baselines and read by people; the guard compares the baselines, not this file.
/// </summary>
internal static class DebtReport
{
    public const string FileName = "DebtReport.md";

    private const int LargestEntries = 15;

    private static readonly Dictionary<string, (string Unit, string Target)> Units = new(StringComparer.Ordinal)
    {
        [DebtMeasures.StaticLookupsFile] = ("uses", "none: GameServices and FacadeAccessor deleted"),
        [DebtMeasures.LargeTypesFile] = ("lines", $"none over {DebtLimits.TypeLines:N0} lines"),
        [DebtMeasures.LongMethodsFile] = ("lines", $"none over {DebtLimits.MethodLines} lines ({DebtLimits.LayoutMethodLines} for layout)"),
        [DebtMeasures.ServicesPerTypeFile] = ("services", $"none over {DebtLimits.ServicesPerType} services"),
        [DebtMeasures.DeferredResolutionFile] = ("parameters", "none"),
        [DebtMeasures.LogicToContentFile] = ("types", "none"),
        [DebtMeasures.DomainCyclesFile] = ("edges", "none"),
        [DebtMeasures.StaticStateFile] = ("members", "each kept with an approved reason, or removed"),
        [DebtMeasures.UpwardEdgesFile] = ("members", "none: every reference follows the domain order"),
        [DebtMeasures.SinkWorkFile] = ("lines", "none: a sink only forwards")
    };

    /// <summary>The unit of a measure's counts, for messages: <c>uses</c>, <c>lines</c>, <c>services</c>.</summary>
    public static string UnitOf(DebtMeasure measure) => Units.TryGetValue(measure.FileName, out var unit) ? unit.Unit : "count";

    public static string Render(IReadOnlyList<DebtMeasure> measures, ExemptionList exemptions)
    {
        var text = new StringBuilder();
        text.Append("# Phase 5 debt report\n\n");
        text.Append("Generated by `SWLOR.Architecture.Tests` (`Phase5DebtTests`) from the source of `SWLOR.Game.Server.sln` and the compiled\n");
        text.Append("server, together with the baselines beside it. Do not edit it by hand. Regenerate after a change that moves the debt:\n");
        text.Append("`SWLOR_UPDATE_SNAPSHOTS=1 dotnet test SWLOR.Architecture.Tests --no-build`. Plan and targets:\n");
        text.Append("`SWLOR.Game.Server/Readmes/MaintainabilityRefactorPhase5.md`. Exemptions and approved entry points: `Exemptions.json`.\n\n");

        text.Append("| Measure | Baseline | Entries | Total | Target |\n");
        text.Append("|---|---|---:|---:|---|\n");
        foreach (var measure in measures)
        {
            var (unit, target) = Units.TryGetValue(measure.FileName, out var found) ? found : ("count", "none");
            text.Append($"| {measure.Title} | `{measure.FileName}` | {measure.Entries.Count:N0} | {measure.Entries.Sum(entry => entry.Count):N0} {unit} | {target} |\n");
        }

        foreach (var measure in measures)
        {
            text.Append($"\n## {measure.Title}\n\n");
            foreach (var line in measure.Summary)
                text.Append("- ").Append(line).Append('\n');

            var largest = measure.Entries
                .OrderByDescending(entry => entry.Count)
                .ThenBy(entry => entry.Key, StringComparer.Ordinal)
                .Take(LargestEntries)
                .ToList();
            if (largest.Count == 0)
                continue;

            text.Append($"\nLargest {largest.Count} of {measure.Entries.Count:N0} (all in `{measure.FileName}`):\n\n");
            text.Append($"| Entry | {Capitalized(UnitOf(measure))} | Detail |\n");
            text.Append("|---|---:|---|\n");
            foreach (var entry in largest)
                text.Append($"| `{entry.Key}` | {entry.Count:N0} | {entry.Detail} |\n");
        }

        text.Append("\n## Exemptions\n\n");
        text.Append("Owner decision 1 (2026-11-14) exempts these from the size and services measures (targets 2 and 3):\n\n");
        text.Append("| Category | Match | Measures | Reason |\n");
        text.Append("|---|---|---|---|\n");
        foreach (var exemption in exemptions.Exemptions)
            text.Append($"| {exemption.Category} | {exemption.Match} `{exemption.Value}` | {string.Join(", ", exemption.Measures)} | {exemption.Reason} |\n");

        text.Append("\nOwner decision 3 (2026-11-14) keeps these static entry points static:\n\n");
        foreach (var approved in exemptions.ApprovedEntryPoints)
            text.Append($"- `{approved.Type}`: {approved.Reason}\n");

        return text.ToString();
    }

    private static string Capitalized(string text) => text.Length == 0 ? text : char.ToUpperInvariant(text[0]) + text[1..];
}
