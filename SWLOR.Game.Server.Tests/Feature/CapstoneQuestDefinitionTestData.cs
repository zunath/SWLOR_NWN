    public static IReadOnlyDictionary<string, QuestGiver> QuestGivers { get; } = BuildQuestGivers();

    private static IReadOnlyDictionary<string, QuestGiver> BuildQuestGivers()
    {
        var result = new Dictionary<string, QuestGiver>();

        foreach (var line in Lines)
        {
            result[line.Id] = line.QuestGiver;
        }

        return result;
    }

