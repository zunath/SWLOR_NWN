using FluentAssertions;
using Newtonsoft.Json.Linq;
using NUnit.Framework;
using SWLOR.Game.Server.Feature.RecipeDefinition.FabricationRecipeDefinition;
using SWLOR.Game.Server.Service.CraftService;
using SWLOR.Game.Server.Service.PropertyService;
using SWLOR.Game.Server.Service.SkillService;

namespace SWLOR.Game.Server.Tests.Feature;

/// <summary>The Fabrication recipes for the Market Stall and the Traveler's Lodge (slice 4e).</summary>
public class CityStallAndLodgeRecipeTests
{
    private static readonly Dictionary<RecipeType, RecipeDetail> Recipes = new CityStallAndLodgeRecipes().BuildRecipes();

    [Test]
    public void ThereAreTwoRecipes_OneForTheStallAndOneForTheLodge_InTheReservedRange()
    {
        Recipes.Keys.Should().BeEquivalentTo(new[] { RecipeType.MarketStall, RecipeType.TravelersLodge });
        ((int)RecipeType.MarketStall).Should().Be(8013);
        ((int)RecipeType.TravelersLodge).Should().Be(8014);
        Recipes.Keys.Should().OnlyContain(type => (int)type >= 8013 && (int)type <= 8039, "this slice owns 8013-8039");
    }

    [Test]
    public void EachRecipe_MakesTheItemOfItsStructureType_AsAFabricationStructure()
    {
        Recipes[RecipeType.MarketStall].Resref.Should().Be($"structure_{(int)StructureType.MarketStall}");
        Recipes[RecipeType.TravelersLodge].Resref.Should().Be($"structure_{(int)StructureType.TravelersLodge}");

        foreach (var recipe in Recipes.Values)
        {
            recipe.Skill.Should().Be(SkillType.Fabrication);
            recipe.Category.Should().Be(RecipeCategoryType.Structure);
            recipe.Quantity.Should().Be(1);
            recipe.IsActive.Should().BeTrue();
            recipe.MinigameParameters.Should().NotBeNull("the Fabricator parameters are generated by tools/SWLOR.RecipeParameters");
        }
    }

    [Test]
    public void TheBills_AreTheLevelAndConstructionPartsOfTheHouseRecipeEachResembles_WithoutThePowerUnit()
    {
        // A stall and a tent have no electrics, so neither takes the power unit its model house takes.
        var stall = Recipes[RecipeType.MarketStall];
        stall.Level.Should().Be(27, "the level of Small House Style 2");
        stall.Components.Should().Equal(new Dictionary<string, int> { ["const_parts"] = 2 });

        var lodge = Recipes[RecipeType.TravelersLodge];
        lodge.Level.Should().Be(33, "the level of Medium House Style 1");
        lodge.Components.Should().Equal(new Dictionary<string, int> { ["r_const_parts"] = 2 });

        foreach (var component in stall.Components.Keys.Concat(lodge.Components.Keys))
            File.Exists(Path.Combine(Root, "Module", "uti", component + ".uti.json")).Should().BeTrue(component);
    }

    [Test]
    public void TheModelRecipes_AreTheSmallAndMediumHouseRecipesAtThoseLevels()
    {
        var houses = new StructureRecipes().BuildRecipes();

        houses[RecipeType.SmallHouseStyle2].Level.Should().Be(27);
        houses[RecipeType.SmallHouseStyle2].Components.Should().ContainKey("const_parts").WhoseValue.Should().Be(2);
        houses[RecipeType.MediumHouseStyle1].Level.Should().Be(33);
        houses[RecipeType.MediumHouseStyle1].Components.Should().ContainKey("r_const_parts").WhoseValue.Should().Be(2);
    }

    [TestCase("structure_5102")]
    [TestCase("structure_5103")]
    public void TheStructureItems_NoLongerCarryNoEconomy_BecauseARecipeMakesThem(string resref)
    {
        var item = JObject.Parse(File.ReadAllText(Path.Combine(Root, "Module", "uti", resref + ".uti.json")));

        (item["VarTable"]?["value"] as JArray ?? new JArray()).Should().NotContain(variable => variable["Name"]!["value"]!.Value<string>() == "NO_ECONOMY");
    }

    private static string Root
    {
        get
        {
            var directory = new DirectoryInfo(TestContext.CurrentContext.TestDirectory);
            while (directory != null && !File.Exists(Path.Combine(directory.FullName, "SWLOR.Game.Server.sln")))
                directory = directory.Parent;

            directory.Should().NotBeNull("the repository root should be discoverable from the test directory");
            return directory!.FullName;
        }
    }
}
