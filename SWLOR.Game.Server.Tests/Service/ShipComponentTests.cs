    private static ShipComponentRecipe Recipe(ShipComponentFamily family, int tier) =>
        RevampComponentCatalog.Recipes.Single(x => x.Family == family && x.Tier == tier && x.Trait == ShipComponentTraitType.None);

    [Test]
    public void CraftedVariants_MakeTheSameItemWithTheirOwnNameAndTrait()
    {
        foreach (var group in RevampComponentCatalog.Recipes.GroupBy(x => (x.Family, x.Tier)))
        {
            var plain = group.Single(x => x.Trait == ShipComponentTraitType.None);
            var variants = group.Where(x => x.Trait != ShipComponentTraitType.None).ToList();
            var crafted = ShipTraitRules.Pool(group.Key.Family, ShipTraitKind.Crafted).Select(x => x.Type).ToList();

            variants.Select(x => x.Trait).Should().BeEquivalentTo(crafted, $"{group.Key}: one recipe per crafted variant");
            foreach (var variant in variants)
            {
                variant.Resref.Should().Be(plain.Resref);
                variant.Components.Should().Equal(plain.Components);
                variant.Name.Should().Be($"{plain.Name}: {ShipTraitRules.Get(variant.Trait).Name}");
                ShipTraitRules.VariantTrait(variant.RecipeType).Should().Be(variant.Trait);
            }

            ShipTraitRules.VariantTrait(plain.RecipeType).Should().Be(ShipComponentTraitType.None);
        }

        RevampComponentCatalog.Recipes.Count(x => x.Family == ShipComponentFamily.EnergyEmitter && x.Tier == 1)
            .Should().Be(4, "Focused, Overcharged and Efficient beside the plain emitter (section 14)");
    }

    [Test]
    public void ComponentRecipeDefinition_RegistersEveryRecipeInTheShipComponentCategory()
    {
        var recipes = new ShipComponentRecipes().BuildRecipes();
        recipes.Should().HaveCount(133, "130 generic component recipes and the three rare components (W9b)");

        foreach (var row in RevampComponentCatalog.Recipes)
        {
            var recipe = recipes[row.RecipeType];
            recipe.Skill.Should().Be(row.Skill);
            recipe.Category.Should().Be(RecipeCategoryType.ShipComponent);
            recipe.Resref.Should().Be(row.Resref);
            recipe.Level.Should().Be(row.RecipeLevel);
            recipe.Quantity.Should().Be(1);
            recipe.EnhancementSlots.Should().Be(0);
            recipe.Components.Should().BeEquivalentTo(row.Components.ToDictionary(x => x.Resref, x => x.Quantity));

            if (row.Trait == ShipComponentTraitType.None)
            {
                recipe.Name.Should().BeNull("the plain recipe shows the item's name");
                recipe.EffectLines.Should().BeEmpty();
            }
            else
            {
                recipe.Name.Should().Be(row.Name);
                recipe.EffectLines.Should().ContainSingle().Which.Should().Contain(ShipTraitRules.Get(row.Trait).Description);
            }
        }
    }

