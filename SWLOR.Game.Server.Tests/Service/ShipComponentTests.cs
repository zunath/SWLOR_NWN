    [Test]
    public void EveryFamily_HasOneItemPerTier()
    {
        GenericItems.Should().HaveCount(45);
        foreach (var (family, (shortName, _)) in Families)
        {
            for (var tier = 1; tier <= 5; tier++)
            {
                var item = RevampComponentCatalog.Items.Single(x => x.Family == family && x.Tier == tier);
                item.Resref.Should().Be($"sc_{shortName}_{tier}");
                item.Name.Should().EndWith($"(Tier {tier})");
                ShipTraitRules.ComponentResref(family, tier).Should().Be(item.Resref);
            }
        }
    }

    [Test]
    public void ComponentBlueprints_AreNonStackingEss9ItemsWithTheirNameAndModel()
    {
        var root = FindRepositoryRoot().FullName;
        var models = new Dictionary<ShipComponentFamily, int>();
        foreach (var item in GenericItems)
        {
            var path = Path.Combine(root, "Module", "uti", $"{item.Resref}.uti.json");
            File.Exists(path).Should().BeTrue(item.Resref);
            using var json = JsonDocument.Parse(File.ReadAllText(path));
            var d = json.RootElement;
            d.GetProperty("BaseItem").GetProperty("value").GetInt32().Should().Be(523, $"{item.Resref}: ESS9, one per slot, so each keeps its trait");
            d.GetProperty("Tag").GetProperty("value").GetString().Should().Be(item.Resref);
            d.GetProperty("LocalizedName").GetProperty("value").GetProperty("0").GetString().Should().Be(item.Name);
            var model = d.GetProperty("ModelPart1").GetProperty("value").GetInt32();
            model.Should().BeInRange(229, 237);
            if (models.TryGetValue(item.Family, out var familyModel))
                model.Should().Be(familyModel, $"{item.Resref}: every tier of a family shares its art");
            models[item.Family] = model;
            d.GetProperty("Cost").GetProperty("value").GetInt32().Should().BePositive();
        }

        models.Values.Should().OnlyHaveUniqueItems("each family has its own art");
    }

