    [Test]
    public void CraftedVariants_MakeTheSameItemWithTheirOwnNameAndTrait()
    {
        foreach (var group in RevampComponentCatalog.Recipes.GroupBy(x => (x.Family, x.Tier)))
        {
            var plain = group.Single(x => x.Trait == ShipComponentTraitType.None);
            var variants = group.Where(x => x.Trait != ShipComponentTraitType.None).ToList();
            var crafted = ShipTraitRules.Pool(group.Key.Family, ShipTraitKind.Crafted).Select(x => x.Type).ToList();

            variants.Select(x => x.Trait).Should().BeEquivalentTo(crafted, $"{group.Key}: one recipe per crafted variant");
            foreach (var variant in variants)
            {
                variant.Resref.Should().Be(plain.Resref);
                variant.Components.Should().Equal(plain.Components);
                variant.Name.Should().Be($"{plain.Name}: {ShipTraitRules.Get(variant.Trait).Name}");
                ShipTraitRules.VariantTrait(variant.RecipeType).Should().Be(variant.Trait);
            }

            ShipTraitRules.VariantTrait(plain.RecipeType).Should().Be(ShipComponentTraitType.None);
        }

        RevampComponentCatalog.Recipes.Count(x => x.Family == ShipComponentFamily.EnergyEmitter && x.Tier == 1)
            .Should().Be(4, "Focused, Overcharged and Efficient beside the plain emitter (section 14)");
    }

