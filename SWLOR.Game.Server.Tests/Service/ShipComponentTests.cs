    private static DirectoryInfo FindRepositoryRoot()
    {
        var directory = new DirectoryInfo(TestContext.CurrentContext.TestDirectory);
        while (directory != null)
        {
            if (File.Exists(Path.Combine(directory.FullName, "SWLOR.Game.Server.sln")) &&
                Directory.Exists(Path.Combine(directory.FullName, "SWLOR.Game.Server")))
                return directory;

            directory = directory.Parent;
        }

        throw new DirectoryNotFoundException("Could not locate the SWLOR_NWN repository root.");
    }

    private static bool IsRare(ShipComponentFamily family) => RevampComponentCatalog.RareFamilies.Contains(family);

    private static IEnumerable<ShipComponentItem> GenericItems => RevampComponentCatalog.Items.Where(x => !IsRare(x.Family));

    private static IEnumerable<ShipComponentRecipe> GenericRecipes => RevampComponentCatalog.Recipes.Where(x => !IsRare(x.Family));

    private static ShipComponentFamily FamilyOf(string resref) =>
        RevampComponentCatalog.Items.Single(x => x.Resref == resref).Family;

    private static int TierOf(string resref) => RevampComponentCatalog.Items.Single(x => x.Resref == resref).Tier;

    /// <summary>Material units of a recipe bill, a component counting as its plain recipe's materials.</summary>
    private static int Units((string Resref, int Quantity)[] bill)
    {
        var total = 0;
        foreach (var (resref, quantity) in bill)
        {
            if (!ShipTraitRules.IsComponent(resref))
            {
                total += quantity;
                continue;
            }

            var plain = RevampComponentCatalog.Recipes.Single(x => x.Resref == resref && x.Trait == ShipComponentTraitType.None);
            total += quantity * plain.Components.Sum(x => x.Quantity);
        }

        return total;
    }

