    [Test]
    public void EveryModuleRecipe_TakesItsFamilysComponentOfItsTier()
    {
        foreach (var step in RevampModuleCatalog.Steps.Where(x => !x.Named))
        {
            var components = step.Components.Where(x => ShipTraitRules.IsComponent(x.Resref)).ToList();
            components.Should().ContainSingle(step.Tag);
            var (resref, quantity) = components[0];
            FamilyOf(resref).Should().Be(ModuleComponent[step.Family], step.Tag);
            TierOf(resref).Should().Be(Math.Min(5, step.Rank / 10 + 1), step.Tag);
            quantity.Should().Be(step.Capital ? 2 : 1, step.Tag);
        }

        RevampModuleCatalog.Steps.Select(x => x.Family).Distinct().Should().BeEquivalentTo(ModuleComponent.Keys,
            "every module family has a component");
    }

    [Test]
    public void EveryHullRecipe_TakesFramesAReactorThrustersAndItsRoleComponents()
    {
        var roleComponents = new Dictionary<ShipRole, ShipComponentFamily[]>
        {
            [ShipRole.Fighter] = new[] { ShipComponentFamily.EnergyEmitter },
            [ShipRole.Interceptor] = new[] { ShipComponentFamily.SensorSuite },
            [ShipRole.Bomber] = new[] { ShipComponentFamily.OrdnanceAssembly },
            [ShipRole.Explorer] = new[] { ShipComponentFamily.SensorSuite },
            [ShipRole.Gunship] = new[] { ShipComponentFamily.ShieldProjector },
            [ShipRole.Logistics] = new[] { ShipComponentFamily.ShieldProjector },
            [ShipRole.MiningBarge] = new[] { ShipComponentFamily.ExtractionHead },
            [ShipRole.LightFreighter] = new[] { ShipComponentFamily.LifeSupportSystem },
            [ShipRole.BlockadeRunner] = new[] { ShipComponentFamily.LifeSupportSystem },
            [ShipRole.Frigate] = new[] { ShipComponentFamily.EnergyEmitter },
            [ShipRole.Industrial] = new[] { ShipComponentFamily.ExtractionHead },
            [ShipRole.HeavyFreighter] = new[] { ShipComponentFamily.LifeSupportSystem },
            [ShipRole.Cruiser] = new[] { ShipComponentFamily.EnergyEmitter, ShipComponentFamily.LifeSupportSystem },
            [ShipRole.CommandShip] = new[] { ShipComponentFamily.SensorSuite, ShipComponentFamily.LifeSupportSystem },
        };
        var frames = new Dictionary<ShipSize, int> { [ShipSize.Small] = 1, [ShipSize.Medium] = 2, [ShipSize.Large] = 3, [ShipSize.Capital] = 4 };

        foreach (var hull in RevampShipCatalog.Hulls)
        {
            var parts = hull.Components.Where(x => ShipTraitRules.IsComponent(x.Resref))
                .ToDictionary(x => FamilyOf(x.Resref), x => x.Quantity);
            var expected = new Dictionary<ShipComponentFamily, int>
            {
                [ShipComponentFamily.HullFrame] = frames[hull.Size],
                [ShipComponentFamily.ShipReactor] = 1,
                [ShipComponentFamily.ThrusterAssembly] = hull.Role is ShipRole.Interceptor or ShipRole.BlockadeRunner ? 2 : 1,
            };
            foreach (var family in roleComponents[hull.Role])
                expected[family] = 1;

            parts.Should().BeEquivalentTo(expected, hull.Tag);
            var tier = Math.Min(5, hull.PilotingRank / 10 + 1);
            hull.Components.Where(x => ShipTraitRules.IsComponent(x.Resref))
                .Should().OnlyContain(x => TierOf(x.Resref) == tier, hull.Tag);
        }
    }

