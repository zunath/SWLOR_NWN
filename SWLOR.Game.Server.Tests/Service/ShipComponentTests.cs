    [Test]
    public void ComponentRecipes_FollowTheHullsAndSalvageFamiliesWithoutMovingAnyEarlierNumber()
    {
        var recipes = GenericRecipes.ToList();
        recipes.Should().HaveCount(130, "9 families x 5 tiers, plain plus 17 crafted variants per tier");
        var first = RevampModuleCatalog.Steps.Where(x => x.Family is not (ShipModuleFamily.ProbeLauncher or ShipModuleFamily.DataAnalyzer or ShipModuleFamily.CloakingDevice) && !x.Named).Select(x => (int)x.RecipeType)
            .Concat(RevampShipCatalog.Hulls.Select(x => (int)x.RecipeType)).Max() + 1;
        first.Should().BeGreaterThan(7347);
        recipes.Select(x => (int)x.RecipeType).Should().Equal(Enumerable.Range(first, 130), "numbered after every module and hull");
        ((int)RecipeType.ShipGasHarvester45).Should().Be(7347, "the W6a recipes keep their numbers");
        ((int)RecipeType.ShipDeedRepublicCenturion).Should().Be(7327);

        var all = RevampModuleCatalog.Steps.Select(x => x.RecipeType)
            .Concat(RevampShipCatalog.Hulls.Select(x => x.RecipeType))
            .Concat(recipes.Select(x => x.RecipeType)).ToList();
        all.Should().OnlyHaveUniqueItems();
    }

    [Test]
    public void ComponentRecipes_UseTheFamilysSkillAndTwoMaterialsOfTheirTier()
    {
        foreach (var recipe in GenericRecipes)
        {
            recipe.Skill.Should().Be(Families[recipe.Family].Skill, recipe.RecipeType.ToString());
            recipe.Resref.Should().Be(ShipTraitRules.ComponentResref(recipe.Family, recipe.Tier));
            recipe.RecipeLevel.Should().Be(Math.Max(2, 10 * (recipe.Tier - 1)), "levels follow the rank schedule");
            recipe.Components.Should().HaveCount(2, recipe.RecipeType.ToString());
            recipe.Components.Sum(x => x.Quantity).Should().Be(2, "a component stands in for two material units");
            recipe.Components.Should().NotContain(x => ShipTraitRules.IsComponent(x.Resref));
        }
    }

