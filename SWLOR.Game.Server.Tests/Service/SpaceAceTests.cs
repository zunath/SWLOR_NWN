    private static readonly Dictionary<string, SpawnTable> SpawnTables = new SpaceSpawnDefinition().BuildSpawnTables();

    private static readonly string[] OrbitAreas =
    {
        "viscaraorbit", "narshadorbit", "moncalaorbit", "hutlar_orbit", "tatooineorbit", "space_dathomir",
        "dantooineorbit", "space_midrim1", "space_midrim2", "space_korriban", "eshanorbit",
    };

    private static readonly string[] ZoneAreas = { "space_viscbelt", "space_midrimneb", "space_korrdebris" };

    private static IEnumerable<ShipAce> Aces => RevampAceCatalog.Aces;

    [Test]
    public void Aces_OnePerOrbitZoneAndWildSpaceSystemEachInItsAreasOwnSpawnTable()
    {
        Aces.Select(x => x.AreaResref).Should().BeEquivalentTo(OrbitAreas.Concat(ZoneAreas).Concat(WildSpaceTuning.Systems.Select(x => x.AreaResref)));
        Aces.Where(x => x.WildSpace).Select(x => x.AreaResref).Should().BeEquivalentTo(WildSpaceTuning.Systems.Select(x => x.AreaResref));
        foreach (var system in WildSpaceTuning.Systems)
            Aces.Single(x => x.AreaResref == system.AreaResref).SpawnTable.Should().Be(system.SpawnTable);
        Aces.Select(x => x.SpawnTable).Should().OnlyHaveUniqueItems("one ace per spawn table, so one per area");
        Aces.Select(x => x.Tag).Should().OnlyHaveUniqueItems();

        foreach (var ace in Aces)
        {
            AreaSpawnTable(ace.AreaResref).Should().Be(ace.SpawnTable, ace.Tag);
            ace.Tag.Length.Should().BeLessThanOrEqualTo(16);
            ShipAceRules.Get(ace.Tag).Should().BeSameAs(ace);
        }

        foreach (var area in OrbitAreas.Concat(ZoneAreas).Concat(WildSpaceTuning.Systems.Select(x => x.AreaResref)))
            Aces.Count(x => AreaSpawnTable(x.AreaResref) == AreaSpawnTable(area)).Should().Be(1, area);
    }

    [Test]
    public void AcePresets_AreElitesOfTheirTiersTopLevelInTheirRole()
    {
        foreach (var ace in Aces)
        {
            var preset = RevampNpcShipCatalog.Ships.Single(x => x.CreatureTag == ace.Tag);
            preset.Difficulty.Should().Be(RevampAceCatalog.AceDifficulty);
            preset.Level.Should().Be(ace.WildSpace ? 52 : ace.Tier * 10).And.Be(ace.Level);
            preset.Role.Should().Be(ace.Role);
            ShipNpcRoleRules.ParseRole(preset.Role).Should().NotBe(ShipNpcRole.Invalid, ace.Tag);
            preset.Size.Should().Be(ShipSize.Medium, "the Elite hull class, as every Elite preset");
            (preset.Hull + preset.Shield).Should().BeLessThan(32767, "the 16-bit HP limit (NpcHitPoints.md)");
            preset.Weapons.Should().NotBeEmpty(ace.Tag);
            preset.Support.Should().BeEmpty(ace.Tag);

            if (ace.WildSpace)
            {
                ace.Tier.Should().Be(WildSpaceTuning.ContentTier, "Wild Space content uses tier 5 for every tier-indexed table");
                preset.Level.Should().Be(RevampNpcShipCatalog.Ships.Single(x => x.CreatureTag == "rrgunship").Level,
                    "a Wild Space ace is an Elite at the Rift Raiders' level");
                continue;
            }

            var platform = RevampNpcShipCatalog.Ships.Single(x => x.CreatureTag == $"t{ace.Tier}platform");
            (preset.Level, preset.Difficulty).Should().Be((platform.Level, platform.Difficulty),
                "an ace is an Elite at its tier's Defense Platform level");
        }

        var registered = new NPCSpaceObjectDefinition().BuildSpaceObjects();
        foreach (var ace in Aces)
            registered[ace.Tag].ShipItemTag.Should().Be(ace.ShipItemTag);
    }

    [Test]
    public void AceSpawns_AreRareAtAGroundRaresShareOfTheirTable()
    {
        foreach (var ace in Aces)
        {
            var table = SpawnTables[ace.SpawnTable];
            var entry = table.Spawns.Should().ContainSingle(x => x.Resref == ace.Tag).Subject;
            entry.IsRare.Should().BeTrue(ace.Tag);
            entry.Type.Should().Be(SWLOR.NWN.API.NWScript.Enum.ObjectType.Creature);
            table.Spawns.Where(x => x.IsRare).Should().ContainSingle(ace.SpawnTable);
            ShipAceRules.IsRareShare(entry.Weight, table.Spawns.Sum(x => x.Weight)).Should().BeTrue(
                $"{ace.Tag} weighs {entry.Weight} of {table.Spawns.Sum(x => x.Weight)}");

            SpawnTables.Where(x => x.Key != ace.SpawnTable)
                .Should().OnlyContain(x => x.Value.Spawns.All(s => s.Resref != ace.Tag), $"{ace.Tag} spawns in its own area only");
        }

        // The normal weights stay as they were.
        SpawnTables["SPACE_VISCARA_ORBIT"].Spawns.Single(x => x.Resref == "t1fighter").Weight.Should().Be(38400);
        SpawnTables["SPACE_KORRIBAN_DEBRIS"].Spawns.Single(x => x.Resref == "t5minelayer").Weight.Should().Be(3840);
        SpawnTables["SPACE_KORRIBAN_DEBRIS"].Spawns.Single(x => x.Resref == "mandocap3").Weight.Should().Be(1);
    }

    [TestCase("SPACE_NARSHADDAA_ORBIT", "SPACE_VISCARA_ORBIT")]
    [TestCase("SPACE_MIDRIM_1", "SPACE_DATHOMIR_ORBIT")]
    [TestCase("SPACE_MIDRIM_2", "SPACE_KORRIBAN_ORBIT")]
    [TestCase("SPACE_DANTOOINE_ORBIT", "SPACE_DATHOMIR_ORBIT")]
    public void AreaTables_SpawnTheShipsOfTheTableTheyUsedToShare(string table, string parent)
    {
        // The ace is the area's own, and so are the Hutt Cartel enforcers on the Smuggler's Moon lanes (W11b).
        static IEnumerable<(string, int, bool)> Ships(SpawnTable t) =>
            t.Spawns.Where(x => !x.IsRare && !HuttEnforcerRules.IsEnforcer(x.Resref)).Select(x => (x.Resref, x.Weight, x.IsRare)).OrderBy(x => x.Resref);

        Ships(SpawnTables[table]).Should().Equal(Ships(SpawnTables[parent]));
    }

    [Test]
    public void AceBlueprints_CopyTheirTiersGunshipWithTheirDesignLootAndAceLocal()
    {
        var appearances = new Dictionary<int, string>();
        foreach (var path in Directory.EnumerateFiles(Path.Combine(Root(), "Module", "utc"), "*.utc.json"))
        {
            using var other = JsonDocument.Parse(File.ReadAllText(path));
            var resref = Path.GetFileName(path).Replace(".utc.json", string.Empty);
            if (!resref.StartsWith("ace_"))
                appearances[other.RootElement.GetProperty("Appearance_Type").GetProperty("value").GetInt32()] = resref;
        }

        foreach (var ace in Aces)
        {
            using var utc = ReadCreature(ace.Tag);
            var d = utc.RootElement;
            d.GetProperty("Tag").GetProperty("value").GetString().Should().Be(ace.Tag);
            d.GetProperty("TemplateResRef").GetProperty("value").GetString().Should().Be(ace.Tag);
            d.GetProperty("FirstName").GetProperty("value").GetProperty("0").GetString().Should().Be(ace.Name);
            var appearance = d.GetProperty("Appearance_Type").GetProperty("value").GetInt32();
            appearance.Should().Be((int)ace.Appearance);
            appearances.Should().NotContainKey(appearance, $"{ace.Tag} flies a Hull Design no other creature uses");

            Skin(d).Should().Be(ace.WildSpace ? "rrskin" : $"t{ace.Tier}hvyskin", "the tier's Gunship and Defense Platform skin sets the level");
            Local(d, "LOOT_TABLE_1").Should().Be(ace.WildSpace ? "SPACE_ELITE_WS, 66, 5" : $"SPACE_ELITE_T{ace.Tier}, 66, 5");
            Local(d, "LOOT_TABLE_2").Should().Be($"{ace.LootTable}, 100, 1", "one guaranteed unique drop");
            Local(d, "LOOT_TABLE_3").Should().Be($"{ace.LootTable}, {RevampAceCatalog.SecondRollPercent}, 1",
                "one more low-chance unique drop");
            Local(d, ShipAceRules.AceVariable).Should().Be("1", "the ace's wreck keeps a data core");
        }

        ShipAceRules.AceVariable.Should().Be("SPACE_ACE", "the space slicing update reads this creature local");
    }

    [Test]
    public void AceLootTables_HoldTheirDesignModuleSchematicTrophyAndComponents()
    {
        var tables = new SpaceAceLootTableDefinition().BuildLootTables();
        tables.Keys.Should().BeEquivalentTo(Aces.Select(x => x.LootTable));
        var moduleSchematics = RevampRewardCatalog.ModuleSchematics.Select(x => x.Resref).ToHashSet();

        foreach (var ace in Aces)
        {
            var table = tables[ace.LootTable];
            table.IsRare.Should().BeTrue(ace.LootTable);
            table.Should().HaveCount(6).And.OnlyContain(x => x.IsRare && x.MaxQuantity == 1);

            var design = RevampRewardCatalog.HullDesigns.Single(x => x.Resref == ace.DesignResref);
            design.Appearance.Should().Be(ace.Appearance, "an ace drops the Design Schematic of the design it flies");
            design.Tier.Should().BeLessThanOrEqualTo(ace.Tier);
            if (!ace.WildSpace)
                design.WildSpaceOnly.Should().BeFalse("only a Wild Space ace may drop a Wild Space only design");
            Weight(table, ace.DesignResref).Should().Be(RevampAceCatalog.DesignWeight);

            if (ace.WildSpace)
                ace.ModuleSchematicResref.Should().Be("proto_tech", "a Wild Space ace drops Prototype Tech in the Module Schematic slot");
            else
                moduleSchematics.Should().Contain(ace.ModuleSchematicResref);
            Weight(table, ace.ModuleSchematicResref).Should().Be(RevampAceCatalog.ModuleSchematicWeight);
            Weight(table, ace.TrophyResref).Should().Be(RevampAceCatalog.TrophyWeight);

            var key = ace.WildSpace ? "rift_key_t55" : RiftRunRules.KeyForTier(ace.Tier).Resref;
            table.Select(x => x.Resref).Should().Equal(ace.DesignResref, ace.ModuleSchematicResref, ace.TrophyResref,
                ace.RareComponentResref, ace.ManufacturerComponentResref, key);
            Weight(table, key).Should().Be(RevampAceCatalog.RiftKeyWeight, "an ace drops its tier's Rift Key");
            var rare = table[3];
            rare.Weight.Should().Be(RevampAceCatalog.RareComponentWeight);
            rare.OnSpawn.Should().NotBeNull("the component is stamped with its rare trait");
            ShipTraitRules.IsComponent(ace.RareComponentResref).Should().BeTrue();
            ace.RareComponentResref.Should().Be(ShipTraitRules.ComponentResref(ShipTraitRules.FamilyOf(ace.RareComponentResref), ace.Tier));
            var trait = ShipTraitRules.Get(ace.RareTrait);
            trait.Kind.Should().Be(ShipTraitKind.Rare);
            trait.Families.Should().Contain(ShipTraitRules.FamilyOf(ace.RareComponentResref));

            var maker = table[4];
            maker.Weight.Should().Be(RevampAceCatalog.ManufacturerComponentWeight);
            maker.OnSpawn.Should().NotBeNull();
            var component = ShipManufacturerRules.Component(ace.Manufacturer);
            (component.Resref, component.Trait).Should().Be((ace.ManufacturerComponentResref, ace.ManufacturerTrait));
            ShipManufacturerRules.WreckManufacturer(ace.Tag).Should().Be(ace.Manufacturer, "its wreck yields its maker's part");
        }

        Aces.Select(x => x.DesignResref).Should().OnlyHaveUniqueItems();
        Aces.Where(x => !x.WildSpace).Select(x => x.ModuleSchematicResref).Should().OnlyHaveUniqueItems();
        Aces.Where(x => x.WildSpace).Should().HaveCount(6).And.OnlyContain(x => x.Manufacturer == ShipManufacturer.RiftRaider);
        Aces.Where(x => x.WildSpace).Select(x => (int)x.Achievement).Should().Equal(240, 241, 242, 243, 244, 245);
        Aces.Select(x => x.TrophyResref).Should().OnlyHaveUniqueItems();
        Aces.Select(x => x.Achievement).Should().OnlyHaveUniqueItems();
    }

    [Test]
    public void Trophies_AreActiveStructuresThatPlaceTheirOwnExistingPlaceable()
    {
        var others = Enum.GetValues<StructureType>()
            .Where(x => Aces.All(a => a.Trophy != x))
            .Select(x => x.GetAttribute<StructureType, StructureAttribute>()?.Resref)
            .ToHashSet();

        foreach (var ace in Aces)
        {
            var detail = ace.Trophy.GetAttribute<StructureType, StructureAttribute>();
            detail.IsActive.Should().BeTrue();
            detail.LayoutType.Should().Be(PropertyLayoutType.Invalid);
            detail.CanBeRetrieved.Should().BeTrue();
            detail.RestrictedPropertyTypes.Should().HaveFlag(PropertyType.House).And.HaveFlag(PropertyType.Starship)
                .And.HaveFlag(PropertyType.City);
            File.Exists(Path.Combine(Root(), "Module", "utp", detail.Resref + ".utp.json")).Should().BeTrue(detail.Resref);
            others.Should().NotContain(detail.Resref, "a trophy looks like no other structure");
            detail.Name.Should().NotContain(ace.Name.Split(' ').Last(), "unique loot is not named after the elite");

            ace.TrophyResref.Should().Be($"structure_{(int)ace.Trophy:0000}", "the structure item resref names its type");
            using var uti = JsonDocument.Parse(File.ReadAllText(Path.Combine(Root(), "Module", "uti", ace.TrophyResref + ".uti.json")));
            var d = uti.RootElement;
            d.GetProperty("BaseItem").GetProperty("value").GetInt32().Should().Be(29);
            d.GetProperty("ModelPart1").GetProperty("value").GetInt32().Should().Be(202, "every structure item shares model 202");
            d.GetProperty("LocalizedName").GetProperty("value").GetProperty("0").GetString().Should().Be(detail.Name);
            d.GetProperty("Tag").GetProperty("value").GetString().Should().Be(ace.TrophyResref);
            if (d.TryGetProperty("VarTable", out var vars))
                vars.GetProperty("value").EnumerateArray()
                    .Should().NotContain(x => x.GetProperty("Name").GetProperty("value").GetString() == "NO_ECONOMY");
        }
    }

    [Test]
    public void SpaceDecor_IsCraftedFurnitureThatPlacesItsOwnExistingPlaceable()
    {
        var decor = new[] { StructureType.CaptainsHolotable, StructureType.StarMapPedestal, StructureType.HoloStarGlobe };
        decor.Select(x => (int)x).Should().Equal(5022, 5023, 5024);
        var others = Enum.GetValues<StructureType>()
            .Where(x => !decor.Contains(x))
            .Select(x => x.GetAttribute<StructureType, StructureAttribute>()?.Resref)
            .ToHashSet();
        var recipes = new SWLOR.Game.Server.Feature.RecipeDefinition.FabricationRecipeDefinition.SpaceDecorRecipes().BuildRecipes();
        var furniture = new SWLOR.Game.Server.Feature.RecipeDefinition.FabricationRecipeDefinition.FurnitureRecipes().BuildRecipes();
        var copies = new Dictionary<StructureType, SWLOR.Game.Server.Service.CraftService.RecipeType>
        {
            [StructureType.CaptainsHolotable] = SWLOR.Game.Server.Service.CraftService.RecipeType.ConsoleCircularCommand,
            [StructureType.StarMapPedestal] = SWLOR.Game.Server.Service.CraftService.RecipeType.HoloDisplay,
            [StructureType.HoloStarGlobe] = SWLOR.Game.Server.Service.CraftService.RecipeType.HoloProjector2,
        };
        var palette = File.ReadAllText(Path.Combine(Root(), "Module", "itp", "itempalcus.itp.json"));

        foreach (var structure in decor)
        {
            var detail = structure.GetAttribute<StructureType, StructureAttribute>();
            detail.IsActive.Should().BeTrue();
            detail.ItemStorage.Should().Be(1, "like every crafted furniture piece");
            detail.RestrictedPropertyTypes.Should().HaveFlag(PropertyType.House).And.HaveFlag(PropertyType.Starship).And.HaveFlag(PropertyType.City);
            File.Exists(Path.Combine(Root(), "Module", "utp", detail.Resref + ".utp.json")).Should().BeTrue(detail.Resref);
            others.Should().NotContain(detail.Resref, "decor looks like no other structure");

            var resref = $"structure_{(int)structure:0000}";
            using var uti = JsonDocument.Parse(File.ReadAllText(Path.Combine(Root(), "Module", "uti", resref + ".uti.json")));
            uti.RootElement.GetProperty("BaseItem").GetProperty("value").GetInt32().Should().Be(29);
            uti.RootElement.GetProperty("ModelPart1").GetProperty("value").GetInt32().Should().Be(202);
            uti.RootElement.GetProperty("LocalizedName").GetProperty("value").GetProperty("0").GetString().Should().Be(detail.Name);
            palette.Should().Contain($"\"{resref}\"");

            var recipe = recipes.Values.Single(x => x.Resref == resref);
            var copied = furniture[copies[structure]];
            recipe.Skill.Should().Be(SWLOR.Game.Server.Service.SkillService.SkillType.Fabrication);
            recipe.Category.Should().Be(copied.Category);
            recipe.Level.Should().Be(copied.Level, "decor copies an existing furniture recipe's level");
            recipe.EnhancementSlots.Should().Be(copied.EnhancementSlots);
            recipe.Components.Should().BeEquivalentTo(copied.Components, "and its bill");
        }

        recipes.Keys.Select(x => (int)x).Should().Equal(7796, 7797, 7798);
    }

    // Helpers

    private static int Weight(IEnumerable<SWLOR.Game.Server.Service.LootService.LootTableItem> table, string resref) =>
        table.Single(x => x.Resref == resref).Weight;

    private static string AreaSpawnTable(string area)
    {
        var text = File.ReadAllText(Path.Combine(Root(), "Module", "git", area + ".git.json"));
        using var git = JsonDocument.Parse(text);
        foreach (var entry in git.RootElement.GetProperty("VarTable").GetProperty("value").EnumerateArray())
        {
            if (entry.GetProperty("Name").GetProperty("value").GetString() == "CREATURE_SPAWN_TABLE_ID")
                return entry.GetProperty("Value").GetProperty("value").GetString();
        }

        return null;
    }

    private static JsonDocument ReadCreature(string resref) =>
        JsonDocument.Parse(File.ReadAllText(Path.Combine(Root(), "Module", "utc", resref + ".utc.json")));

    private static string Skin(JsonElement utc) =>
        utc.GetProperty("Equip_ItemList").GetProperty("value").EnumerateArray()
            .Single(x => x.GetProperty("__struct_id").GetInt32() == 131072)
            .GetProperty("EquippedRes").GetProperty("value").GetString();

    private static string Local(JsonElement d, string name)
    {
        foreach (var entry in d.GetProperty("VarTable").GetProperty("value").EnumerateArray())
            if (entry.GetProperty("Name").GetProperty("value").GetString() == name)
                return entry.GetProperty("Value").GetProperty("value").ToString();
        return null;
    }

    private static string Root()
    {
        for (var dir = new DirectoryInfo(TestContext.CurrentContext.TestDirectory); dir != null; dir = dir.Parent)
            if (File.Exists(Path.Combine(dir.FullName, "SWLOR.Game.Server.sln"))) return dir.FullName;
        throw new DirectoryNotFoundException("Could not locate the repository.");
    }
