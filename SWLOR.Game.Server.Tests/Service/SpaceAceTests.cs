/// <summary>
/// The aces (plan sections 11 and 14): one named rare-spawn pilot per orbit and per Small/Medium zone, with its preset,
/// rare spawn entry, creature blueprint, unique loot table and trophy. Generated by tools/SpaceRevampBalance (rewards.py,
