    [Test]
    public void UnlockedHullDesigns_PersistOnThePlayerRecord()
    {
        var design = HullDesignRules.DesignsFor("sd_republicstrik")[0];
        var player = JsonConvert.DeserializeObject<Player>("{}")!;
        player.UnlockedHullDesigns.Should().NotBeNull("older records load empty");
        HullDesignRules.Unlock(player.UnlockedHullDesigns, design, new DateTime(2026, 10, 27, 0, 0, 0, DateTimeKind.Utc));

