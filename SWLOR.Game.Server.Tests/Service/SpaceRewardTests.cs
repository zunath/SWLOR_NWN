    [Test]
    public void ModuleSchematics_TeachTheirRecipeAndDropFromTheTierFiveAndSixBosses()
    {
        var schematics = RevampRewardCatalog.ModuleSchematics;
        schematics.Should().HaveCount(16);
        var tables = new SpaceLootTableDefinition().BuildLootTables();

        foreach (var schematic in schematics)
        {
            Step(schematic.ModuleTag).RecipeType.Should().Be(schematic.RecipeType);
            using var blueprint = ReadBlueprint(schematic.Resref);
            var d = blueprint.RootElement;
            d.GetProperty("Tag").GetProperty("value").GetString().Should().Be("RECIPE");
            Local(d, "RECIPES").Should().Be(((int)schematic.RecipeType).ToString());
            HasNoEconomy(d).Should().BeFalse(schematic.Resref);

            foreach (var table in new[] { "SPACE_BOSS_T5", "SPACE_BOSS_T6" })
                tables[table].Should().ContainSingle(x => x.Resref == schematic.Resref).Which.Weight.Should().Be(1);
        }

        tables["SPACE_BOSS_T5"].Where(x => !x.Resref.StartsWith("recipe_")).Should().OnlyContain(x => x.Weight == 150,
            "the table's own entries keep their odds");
        tables["SPACE_BOSS_T6"].Where(x => schematics.All(s => s.Resref != x.Resref)).Should().OnlyContain(x => x.Weight == 10);
        var t5 = tables["SPACE_BOSS_T5"];
        (16.0 / t5.Sum(x => x.Weight)).Should().BeLessThan(0.06, "a low rate for now");
    }

