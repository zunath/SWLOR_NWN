    [Test]
    public void AmmoVariants_ChangeTheShotAndAddTheirRider()
    {
        var missile = Step("sm_missl_45");
        var shot = ShipShotBuilder.Build(missile, ShipSize.Small, ShipSize.Small, 10);

        var ion = ShipAmmoRules.Apply(shot, ShipAmmoRules.Variant("ship_missile_ion"));
        ion.DamageType.Should().Be(CombatDamageType.EM);
        ion.Dmg.Should().Be((int)Math.Round(shot.Dmg * 0.9, MidpointRounding.AwayFromZero));
        ion.ShieldDamageMultiplier.Should().Be(1.25);
        ShipAmmoRules.Slows(ShipAmmoRules.Variant("ship_missile_ion"), 5).Should().BeTrue();
        ShipAmmoRules.Slows(ShipAmmoRules.Variant("ship_missile_ion"), 0).Should().BeFalse("only hull hits slow");

        var seeker = ShipAmmoRules.Apply(shot, ShipAmmoRules.Variant("ship_missile_skr"));
        seeker.Accuracy.Should().Be(shot.Accuracy + 20);
        seeker.DamageType.Should().Be(CombatDamageType.Explosive);

        var incendiary = ShipAmmoRules.Variant("ship_missile_inc");
        ShipAmmoRules.Apply(shot, incendiary).DamageType.Should().Be(CombatDamageType.Thermal);
        ShipAmmoRules.BurnTicks(incendiary).Should().Be(3);
        ShipAmmoRules.BurnDamage(50, incendiary).Should().Be(6);
        ShipAmmoRules.BurnDamage(2, incendiary).Should().Be(1, "a burn tick does at least 1");

        var torpedo = ShipShotBuilder.Build(Step("sm_torp_45"), ShipSize.Small, ShipSize.Large, 10);
        var plasma = ShipAmmoRules.Apply(torpedo, ShipAmmoRules.Variant("proton_bomb_pls"));
        plasma.ShieldBypass.Should().BeTrue("torpedo variants still bypass shields");
        plasma.DamageType.Should().Be(CombatDamageType.Thermal);

        ShipAmmoRules.Apply(shot, null).Should().BeSameAs(shot, "plain ammo leaves the shot as it is");
        shot.DamageType.Should().Be(CombatDamageType.Explosive, "the variant works on a copy");
    }

