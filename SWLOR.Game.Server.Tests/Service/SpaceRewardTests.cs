    [Test]
    public void DesignSchematic_UnlocksTheDesignForRefitAndTheShipShowsIt()
    {
        var striker = RevampShipCatalog.Hulls.Single(x => x.Tag == "sd_striker");
        var design = HullDesignRules.DesignsFor("sd_striker")[1];
        var unlocked = new Dictionary<string, DateTime>();

        HullDesignRules.CanRefitTo("sd_striker", striker.Appearance, striker.Appearance, unlocked).Should().BeTrue("Standard always");
        HullDesignRules.CanRefitTo("sd_striker", striker.Appearance, design.Appearance, unlocked).Should().BeFalse();
        HullDesignRules.UnlockedFor("sd_striker", unlocked).Should().BeEmpty();

        HullDesignRules.Unlock(unlocked, design, DateTime.UtcNow).Should().BeTrue();
        HullDesignRules.Unlock(unlocked, design, DateTime.UtcNow).Should().BeFalse("a schematic for a known design is kept");
        HullDesignRules.CanRefitTo("sd_striker", striker.Appearance, design.Appearance, unlocked).Should().BeTrue();
        HullDesignRules.UnlockedFor("sd_striker", unlocked).Should().ContainSingle().Which.Should().BeSameAs(design);
        HullDesignRules.UnlockedFor("sd_condor", unlocked).Should().BeEmpty("a design is for one ship only");

        var other = HullDesignRules.DesignsFor("sd_condor")[0];
        HullDesignRules.CanRefitTo("sd_striker", striker.Appearance, other.Appearance, unlocked).Should().BeFalse();

        HullDesignRules.ShipAppearance("sd_striker", striker.Appearance, 0).Should().Be(striker.Appearance);
        HullDesignRules.ShipAppearance("sd_striker", striker.Appearance, (int)design.Appearance).Should().Be(design.Appearance);
        HullDesignRules.ShipAppearance("sd_striker", striker.Appearance, (int)other.Appearance)
            .Should().Be(striker.Appearance, "another model's design never shows");
        HullDesignRules.DesignName("sd_striker", striker.Appearance, design.Appearance).Should().Be(design.Name);
        HullDesignRules.DesignName("sd_striker", striker.Appearance, striker.Appearance).Should().Be("Standard");
    }

