    // Helpers

    private static JsonDocument ReadBlueprint(string resref) =>
        JsonDocument.Parse(File.ReadAllText(Path.Combine(Root(), "Module", "uti", resref + ".uti.json")));

    private static string Local(JsonElement uti, string name)
    {
        foreach (var entry in uti.GetProperty("VarTable").GetProperty("value").EnumerateArray())
            if (entry.GetProperty("Name").GetProperty("value").GetString() == name)
                return entry.GetProperty("Value").GetProperty("value").ToString();
        return null;
    }

    private static bool HasNoEconomy(JsonElement uti) =>
        uti.TryGetProperty("VarTable", out var table) &&
        table.GetProperty("value").EnumerateArray().Any(x => x.GetProperty("Name").GetProperty("value").GetString() == "NO_ECONOMY");

    private static string Root()
    {
        for (var dir = new DirectoryInfo(TestContext.CurrentContext.TestDirectory); dir != null; dir = dir.Parent)
            if (File.Exists(Path.Combine(dir.FullName, "SWLOR.Game.Server.sln"))) return dir.FullName;
        throw new DirectoryNotFoundException("Could not locate the repository.");
    }
