    private static ShipModuleStep Step(string tag) => RevampModuleCatalog.Steps.Single(x => x.Tag == tag);

    /// <summary>Returns the queued numbers in turn (each below its argument), like Random.Next.</summary>
    private static Func<int, int> Rolls(params int[] values)
    {
        var queue = new Queue<int>(values);
        return max => Math.Min(queue.Count > 0 ? queue.Dequeue() : 0, max - 1);
    }

