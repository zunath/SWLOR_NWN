    /// <summary>Moves kill progress saved under a former group to its current group, keeping an existing entry.</summary>
    public static bool RenameKillProgresses(JObject progresses)
    {
        if (progresses == null) return false;
        var changed = false;
        foreach (var entry in progresses.Properties().ToArray())
        {
            if (!Renames.TryGetValue(entry.Name, out var replacement) &&
                !RemovedNumbers.TryGetValue(entry.Name, out replacement))
                continue;
            var name = replacement.ToString();
            if (progresses.Property(name) == null &&
                progresses.Property(((int)replacement).ToString(CultureInfo.InvariantCulture)) == null)
                progresses[name] = entry.Value.DeepClone();
            entry.Remove();
            changed = true;
        }
        return changed;
    }

    /// <summary>Renames the kill progress of every quest in one raw Player record.</summary>
    public static bool MigratePlayer(JObject player)
    {
        if (player[nameof(Player.Quests)] is not JObject quests) return false;
        var changed = false;
        foreach (var quest in quests.Properties())
            if (quest.Value is JObject state)
                changed |= RenameKillProgresses(state[nameof(PlayerQuest.KillProgresses)] as JObject);
        return changed;
    }
