using System;
using System.Collections.Generic;
using System.Linq;
using SWLOR.Game.Server.Service.StatusEffectService;
using SWLOR.NWN.API.NWScript.Enum;

namespace SWLOR.Game.Server.Service.AstromechService
{
    /// <summary>
    /// The names and icons of the status effects an astromech's abilities apply. An astromech ability is a copy of a
    /// humanoid one and applies the same status effect, so the two never stack on one target. The effect is shown under
    /// the name of the ability that applied it: a Deflector Field from an astromech, Shielding from a medic.
    /// The table is generated by tools/GenerateAstromechSkillMirrors.py from the `statuses` list of its configuration.
    /// </summary>
    public static partial class AstromechStatusEffectNames
    {
        /// <summary>The status effects that carry an astromech name.</summary>
        public static IReadOnlyDictionary<Type, string> All => Entries.ToDictionary(entry => entry.Key, entry => entry.Value.Name);

        /// <summary>
        /// The name of a status effect as applied by an astromech or by anyone else.
        /// </summary>
        public static string Resolve(IStatusEffect statusEffect, bool appliedByAstromech)
        {
            return appliedByAstromech && Entries.TryGetValue(statusEffect.GetType(), out var entry)
                ? entry.Name
                : statusEffect.Name;
        }

        /// <summary>
        /// The name of a status effect as players read it: the astromech name when an astromech applied it.
        /// </summary>
        public static string Resolve(IStatusEffect statusEffect, uint source)
        {
            return Resolve(statusEffect, IsAstromech(source));
        }

        /// <summary>
        /// The icon of a status effect as applied by an astromech or by anyone else.
        /// </summary>
        public static EffectIconType ResolveIcon(IStatusEffect statusEffect, bool appliedByAstromech)
        {
            return appliedByAstromech && Entries.TryGetValue(statusEffect.GetType(), out var entry)
                ? entry.Icon
                : statusEffect.Icon;
        }

        /// <summary>
        /// The icon a status effect shows on its target: the astromech icon when an astromech applied it.
        /// </summary>
        public static EffectIconType ResolveIcon(IStatusEffect statusEffect, uint source)
        {
            return ResolveIcon(statusEffect, IsAstromech(source));
        }

        /// <summary>
        /// True if a status effect of this type can show this icon, under either of its names.
        /// </summary>
        public static bool ShowsIcon(IStatusEffect statusEffect, EffectIconType icon)
        {
            return statusEffect.Icon == icon ||
                   (Entries.TryGetValue(statusEffect.GetType(), out var entry) && entry.Icon == icon);
        }

        private static bool IsAstromech(uint source)
        {
            return GetIsObjectValid(source) && Astromech.IsAstromech(source);
        }
    }
}
