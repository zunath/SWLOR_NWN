    /// <summary>Every resref that has a row.</summary>
    public static IReadOnlyCollection<string> Resrefs => Flavors.Keys;

    public static bool Contains(string resref) => Flavors.ContainsKey(resref);

    /// <summary>The ingredient's effect, or <see cref="Unlisted"/> when it has no row.</summary>
    public static KitchenComponentFlavor Get(string resref) =>
        Flavors.TryGetValue(resref, out var flavor) ? flavor : Unlisted;

    private static KitchenComponentFlavor Flavor(int savory, int sweet, int spice) =>
        new(KitchenIngredientKind.Flavor, new FlavorVector(savory, sweet, spice));
