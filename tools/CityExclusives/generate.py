"""Writes the city-exclusive store items (slice 4e) from tools/CityExclusives/catalog.py.

usage: python tools/CityExclusives/generate.py [--check] [--table]

Writes, all under the repository root:
  * Module/uti/structure_5190..: one structure item per decor piece (the shape of structure_5022, the space decor items)
  * Module/uti/house_*, stall_pie: one food item per house drink and stall dish (a copy of the dish it takes its stats from)
  * Module/itp/itempalcus.itp.json: their palette entries (existing entries with the same resref are replaced)
  * the StructureType block between the "city exclusives" markers

The unlock levels and weekly limits the server uses are in SWLOR.Game.Server/Service/CityStoreService/CityStoreCatalog.cs; keep them
in step with the catalog (CityExclusiveItemTests checks that they match).

--check changes nothing and exits 1 when a file would change. --table prints the items as a markdown table for a pull request.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalog as c  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
UTI_DIR = ROOT / "Module" / "uti"
PALETTE = ROOT / "Module" / "itp" / "itempalcus.itp.json"
STRUCTURE_ENUM = ROOT / "SWLOR.Game.Server" / "Service" / "PropertyService" / "StructureType.cs"
STRUCTURE_TEMPLATE = UTI_DIR / "structure_5022.uti.json"

STRUCTURE_BEGIN = "        // BEGIN city exclusives (generated by tools/CityExclusives/generate.py)"
STRUCTURE_END = "        // END city exclusives"
# The block goes after the planet identity decor when that is in the file, else after the Fermentation Vat.
STRUCTURE_ANCHORS = ("        // END planet identity decor\n", "        FermentationVat = 5105,\n")


def read_bytes_text(path):
    """The file's text with LF line endings; the working copies use CRLF and writing converts back."""
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def write_text(path, text, crlf):
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def uses_crlf(path):
    return b"\r\n" in path.read_bytes() if path.exists() else True


# --- JSON files --------------------------------------------------------------------------------------------------------------------------

def dump_json(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def loc_string(text):
    return {"type": "cexolocstring", "value": {"0": text}}


def structure_item(template, index, piece):
    item = json.loads(json.dumps(template))
    resref = f"structure_{c.structure_id(index)}"
    item["LocalizedName"] = loc_string(piece["name"])
    item["Description"] = loc_string(piece["text"])
    item["DescIdentified"] = loc_string(piece["text"])
    item["Tag"]["value"] = resref
    item["TemplateResRef"]["value"] = resref
    item["Cost"]["value"] = piece["price"]
    item["AddCost"]["value"] = piece["price"]
    return resref, item


def food_item(food):
    item = json.loads(read_bytes_text(UTI_DIR / f"{food['copies']}.uti.json"))
    price = c.food_price(food)
    item["LocalizedName"] = loc_string(food["name"])
    item["Description"] = loc_string(food["text"])
    item["DescIdentified"] = loc_string(food["text"])
    item["TemplateResRef"]["value"] = food["resref"]
    item["Cost"]["value"] = price
    item["AddCost"]["value"] = price
    return food["resref"], item


# --- the palette -------------------------------------------------------------------------------------------------------------------------

def find_list(node, resref):
    """The list of palette entries that holds an entry with this resref."""
    if isinstance(node, dict):
        for value in node.values():
            found = find_list(value, resref)
            if found is not None:
                return found
    elif isinstance(node, list):
        for entry in node:
            if isinstance(entry, dict) and entry.get("RESREF", {}).get("value") == resref:
                return node
        for entry in node:
            found = find_list(entry, resref)
            if found is not None:
                return found
    return None


def palette_entry(name, resref):
    return {"__struct_id": 0, "NAME": {"type": "cexostring", "value": name}, "RESREF": {"type": "resref", "value": resref}}


def is_planet_decor(resref):
    match = re.fullmatch(r"structure_(\d+)", resref)
    return match is not None and 5130 <= int(match.group(1)) <= 5189


def update_palette(palette, structures, foods):
    """Replaces this content's palette entries: structures after Traveler's Lodge (and the planet decor after it), foods in name order."""
    mine = {resref for resref, _ in structures} | {resref for resref, _ in foods}
    structure_list = find_list(palette, "structure_5103")
    food_list = find_list(palette, "waro_potpie")
    assert structure_list is not None and food_list is not None, "palette lists not found"
    for entries in (structure_list, food_list):
        entries[:] = [e for e in entries if e["RESREF"]["value"] not in mine]
    at = next(i for i, e in enumerate(structure_list) if e["RESREF"]["value"] == "structure_5103") + 1
    while at < len(structure_list) and is_planet_decor(structure_list[at]["RESREF"]["value"]):
        at += 1
    structure_list[at:at] = [palette_entry(name, resref) for resref, name in structures]
    for resref, name in foods:
        position = next((i for i, e in enumerate(food_list) if "NAME" in e and e["NAME"]["value"].lower() > name.lower()), len(food_list))
        food_list.insert(position, palette_entry(name, resref))
    return palette


# --- C# ----------------------------------------------------------------------------------------------------------------------------------

def cs_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def structure_block():
    lines = [STRUCTURE_BEGIN,
             "        // Player City Revamp: city-exclusive store decor (slice 4e), inside the reserved 5190-5199. City stores sell these with a",
             "        // weekly allowance (CityStoreCatalog); no recipe makes them."]
    for index, piece in enumerate(c.DECOR):
        lines += [f"        [Structure({cs_string(piece['name'])},",
                  f"            {cs_string(piece['placeable'])},",
                  f"            {cs_string(piece['text'])},",
                  "            true,",
                  f"            {c.DECOR_STORAGE})]",
                  f"        {piece['enum']} = {c.structure_id(index)},",
                  ""]
    lines[-1:] = [STRUCTURE_END]
    return "\n".join(lines) + "\n"


def replace_block(text, begin, end, block, anchors):
    if begin in text:
        start = text.index(begin)
        stop = text.index(end, start) + len(end) + 1
        return text[:start] + block + text[stop:]
    for anchor in anchors:
        if anchor in text:
            at = text.index(anchor) + len(anchor)
            return text[:at] + "\n" + block + text[at:]
    raise SystemExit("anchor not found in the enum file")


# --- assembling --------------------------------------------------------------------------------------------------------------------------

def build():
    """{path: text} for every file this content writes."""
    files = {}
    template = json.loads(read_bytes_text(STRUCTURE_TEMPLATE))
    structures, foods = [], []
    for index, piece in enumerate(c.DECOR):
        resref, item = structure_item(template, index, piece)
        files[UTI_DIR / f"{resref}.uti.json"] = dump_json(item)
        structures.append((resref, piece["name"]))
    for food in c.FOODS:
        resref, item = food_item(food)
        files[UTI_DIR / f"{resref}.uti.json"] = dump_json(item)
        foods.append((resref, food["name"]))

    palette = json.loads(read_bytes_text(PALETTE))
    files[PALETTE] = dump_json(update_palette(palette, structures, foods))

    enum_text = read_bytes_text(STRUCTURE_ENUM)
    files[STRUCTURE_ENUM] = replace_block(enum_text, STRUCTURE_BEGIN, STRUCTURE_END, structure_block(), STRUCTURE_ANCHORS)
    return files


def table():
    rows = ["| Item | Store | Unlocks at | Weekly limit | Price | Copies |", "| --- | --- | --- | --- | --- | --- |"]
    for food in c.FOODS:
        rows.append(f"| {food['name']} | {food['store']} | level {food['level']} | {food['limit']} | {c.food_price(food)} | {food['copies']} (tier {food['tier']}) |")
    for piece in c.DECOR:
        rows.append(f"| {piece['name']} | {piece['store']} | level {piece['level']} | {piece['limit']} | {piece['price']} | placeable {piece['placeable']} |")
    return "\n".join(rows)


def main():
    if "--table" in sys.argv:
        print(table())
        return
    files = build()
    changed = []
    for path, text in files.items():
        if path.exists() and read_bytes_text(path) == text:
            continue
        changed.append(path)
        if "--check" not in sys.argv:
            write_text(path, text, uses_crlf(path) if path.exists() else True)
    for path in changed:
        print(("would change " if "--check" in sys.argv else "wrote ") + str(path.relative_to(ROOT)))
    if "--check" in sys.argv and changed:
        sys.exit(1)
    if not changed:
        print("city exclusives are current")


if __name__ == "__main__":
    main()
