def base_and_level(name):
    match = re.search(r"\s+(I|II|III|IV|V)$", name)
    if not match:
        return name, 1
    return name[: match.start()], ROMAN_LEVELS[match.group(1)]


def pascal(name):
    cleaned = re.sub(r"'s\b", "s", name)
    words = re.findall(r"[A-Za-z0-9]+", cleaned)
    return "".join(word[:1].upper() + word[1:] for word in words)


def escape_csharp(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def base36(value):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    value = int(value)
    if value == 0:
        return "0"

    result = ""
    while value:
        value, remainder = divmod(value, 36)
        result = digits[remainder] + result
    return result


def compact_icon_label(label):
    words = re.findall(r"[A-Za-z0-9]+", label)
    compact = ""
    for word in words:
        lowered = word.lower()
        if lowered.isdigit():
            compact += lowered
            continue

        compact += lowered[0] + re.sub(r"[aeiou]", "", lowered[1:])

    compact = re.sub(r"[^a-z0-9]", "", compact)
    return compact or "perk"


