def load_tlk():
    if not TLK_JSON.exists():
        raise RuntimeError(f"Could not find TLK JSON at {TLK_JSON}")

    tlk = json.loads(TLK_JSON.read_text(encoding="utf-8-sig"))
    entries = tlk.setdefault("entries", [])
    by_text = {}
    by_id = {}

    for entry in entries:
        entry_id = int(entry["id"])
        by_id[entry_id] = entry
        text = entry.get("text", "")
        if text.strip() and text not in by_text:
            by_text[text] = CUSTOM_TLK_OFFSET + entry_id

    return tlk, by_id, by_text


def write_tlk(tlk):
    tlk["entries"] = sorted(tlk["entries"], key=lambda entry: int(entry["id"]))
    TLK_JSON.write_text(
        json.dumps(tlk, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n")


def ensure_tlk_text(tlk, by_id, by_text, text):
    text = text.strip()
    if not text:
        return "****"

    if text in by_text:
        return str(by_text[text])

    entries = tlk["entries"]
    blank_entry = next(
        (entry for entry in sorted(entries, key=lambda entry: int(entry["id"]))
         if not entry.get("text", "").strip()),
        None)

    if blank_entry is not None:
        entry_id = int(blank_entry["id"])
        blank_entry["text"] = text
    else:
        used_ids = set(by_id)
        max_id = max(used_ids) if used_ids else 0
        gap_id = next((candidate for candidate in range(max_id + 1) if candidate not in used_ids), None)
        entry_id = gap_id if gap_id is not None else max_id + 1
        entry = {"id": entry_id, "text": text}
        entries.append(entry)
        by_id[entry_id] = entry

    str_ref = CUSTOM_TLK_OFFSET + entry_id
    by_text[text] = str_ref
    return str(str_ref)


def ensure_tlk_text_preserving_matching_ref(tlk, by_id, by_text, current_ref, text):
    """Keep an existing custom TLK ref when it already resolves to the requested text.

    The TLK contains intentional duplicate text in legacy and newer slots. Relinking a working
    2DA row to a different duplicate creates noisy unrelated asset changes and can invalidate a
    deployed TLK/2DA pairing even though the visible text is identical.
    """
    text = text.strip()
    if current_ref.isdigit():
        entry_id = int(current_ref) - CUSTOM_TLK_OFFSET
        existing = by_id.get(entry_id)
        if existing is not None and existing.get("text", "").strip() == text:
            return current_ref

    return ensure_tlk_text(tlk, by_id, by_text, text)


def ensure_status_effect_tlk_entries(tlk, by_id, by_text):
    status_dir = ROOT / "SWLOR.Game.Server" / "Feature" / "StatusEffectDefinition"
