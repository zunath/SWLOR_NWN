def parse_int(value):
    value = value.strip()
    if not value or value == "-":
        return 0

    parsed = float(value)
    if not parsed.is_integer():
        raise ValueError(f"Expected a whole number, got {value!r}")
    return int(parsed)


def parse_seconds(value):
    value = value.strip()
    if not value or value == "-" or value.lower() == "instant":
        return 0.0
    total = 0
    for amount, unit in re.findall(r"(\d+)\s*(minute|minutes|second|seconds)", value, re.IGNORECASE):
        total += int(amount) * (60 if unit.lower().startswith("minute") else 1)
    return float(total)


def parse_skill_rank(value):
    match = re.search(r"(\d+)", value)
    if not match:
        raise RuntimeError(f"Could not parse skill rank from {value!r}")
    return int(match.group(1))


def parse_damage(description, level):
    if "area combat abilities restore" in description.lower():
        return 0

    if re.search(r"^\s*For \d+ seconds, ranged hits add Suppression stacks", description, re.IGNORECASE):
        return 0

    patterns = [
        r"weapon DMG \+ (\d+)",
        r"weapon damage \+ (\d+)",
        r"(?:deal|deals|dealing) (\d+) (?:Force )?DMG",
        r"\+(\d+) DMG",
    ]
    for pattern in patterns:
        match = re.search(pattern, description, re.IGNORECASE)
        if match:
            return int(match.group(1))
    return 8 + (level - 1) * 10


def parse_duration(description):
    match = re.search(r"for (\d+) seconds", description, re.IGNORECASE)
    return int(match.group(1)) if match else 0


def parse_suppression_stack_evasion_penalty(description):
    patterns = [
        r"reducing Evasion by (\d+)% per stack",
        r"Suppression stacks reduce Evasion by (\d+)%",
    ]
    for pattern in patterns:
        match = re.search(pattern, description, re.IGNORECASE)
        if match:
            return int(match.group(1))

    return 0


def status_types(description):
    result = []
    for keyword, status_type in STATUS_KEYWORDS:
        if re.search(rf"\b{re.escape(keyword)}\b", description, re.IGNORECASE) and status_type not in result:
            result.append(status_type)
    return result


def first_int(pattern, description, default=0, flags=re.IGNORECASE):
    match = re.search(pattern, description, flags)
    return int(match.group(1)) if match else default


def primary_status_factory(description, primary_status):
    if primary_status == "SunderStatusEffect":
        percent = first_int(r"reducing .*?Defense by (\d+)%", description)
        if percent:
            return f"() => new SunderStatusEffect({percent})"
    if primary_status == "ExposedStatusEffect":
        percent = first_int(r"reducing .*?Defense by (\d+)%", description)
        if percent:
            return f"() => new ExposedStatusEffect(-{percent})"
    if primary_status == "WeakenedStatusEffect":
        percent = first_int(r"reduc(?:es|ing) .*?Attack by (\d+)%", description)
        if percent:
            return f"() => new WeakenedStatusEffect({percent})"
    if primary_status == "DisorientedStatusEffect":
        percent = first_int(r"reducing Accuracy and Evasion by (\d+)%", description)
        if percent:
            return f"() => new DisorientedStatusEffect({percent}, {percent})"
    if primary_status == "FoggyMindStatusEffect":
        accuracy_penalty = first_int(r"-(\d+)% Ability Accuracy", description)
        if accuracy_penalty:
            return f"() => new FoggyMindStatusEffect(1, {accuracy_penalty})"
    if primary_status == "PoisonResistancePenaltyStatusEffect":
        penalty = first_int(r"inflicts -(\d+) Poison Resistance", description)
        if penalty:
            return f"() => new PoisonResistancePenaltyStatusEffect(-{penalty})"

    return None


