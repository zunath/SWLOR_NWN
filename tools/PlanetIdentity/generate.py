"""Writes the planet identity content (slice 5g) from tools/PlanetIdentity/catalog.py.

usage: python tools/PlanetIdentity/generate.py [--check]

Writes, all under the repository root:
  * Module/uti/structure_5130..: one structure item per decor piece (the shape of structure_5022, the space decor items)
  * Module/uti/sig_*_dish / sig_*_drink: one food item per signature dish and drink (a copy of the dish it takes its stats from)
  * Module/itp/itempalcus.itp.json: their palette entries (existing entries with the same resref are replaced)
  * the StructureType and RecipeType blocks between the "planet identity" markers
  * SWLOR.Game.Server/Feature/RecipeDefinition/FabricationRecipeDefinition/PlanetDecorRecipes.cs and
    CookingRecipeDefinition/PlanetSignatureRecipes.cs

Run order after a change to the catalog:
  1. python tools/PlanetIdentity/generate.py
  2. dotnet run --project tools/SWLOR.RecipeParameters -p:RunPostBuildEvent=Never -- write Kitchen    (and: write Fabricator)
     The generated recipe files carry no minigame parameters; the tool adds them, and the values are deterministic for a recipe name.
  3. python tools/UpdatePlanetIdentityBible.py
  4. dotnet run --project tools/SWLOR.RecipeParameters -p:RunPostBuildEvent=Never -- export <data.json>, then
     python tools/UpdateRecipeParameterBible.py --data <data.json>

--check changes nothing and exits 1 when a file would change.
"""
