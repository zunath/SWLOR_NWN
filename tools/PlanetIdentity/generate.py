# --- assembling ------------------------------------------------------------------------------------------------------------------------

def replace_block(text, begin, end, block, anchor):
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end) + r"\n", re.S)
    if pattern.search(text):
        return pattern.sub(lambda _m: block, text, count=1)
    if not anchor.search(text):
        raise SystemExit("enum anchor not found")
    return anchor.sub(lambda m: m.group(1) + "\n" + block, text, count=1)


def with_existing_parameters(path, text):
    """A regenerated recipe file keeps the minigame parameters the recipe parameter tool already wrote into it."""
    if not path.exists():
        return text
    existing = {}
    for match in re.finditer(r"_builder\.Create\(RecipeType\.(\w+),(?:(?!_builder\.Create).)*?(\.(?:Kitchen|Fabricator)Parameters\([^;]*\));", read_text(path), re.S):
        existing[match.group(1)] = match.group(2)
    if not existing:
        return text

    def attach(match):
        recipe = match.group(1)
        return match.group(0) if recipe not in existing else match.group(0)[:-1] + "\n                " + existing[recipe] + ";"

    return re.sub(r"_builder\.Create\(RecipeType\.(\w+),.*?\.Component\([^;]*;", attach, text, flags=re.S)


def build():
    """Every file this generator owns, as path -> text."""
    files = {}
    palette = load_json(PALETTE)
    template = load_json(STRUCTURE_TEMPLATE)
    structures, foods = [], []
    for si, entry in enumerate(c.SETS):
        place = c.place_name(entry)
        for pi, piece in enumerate(entry["decor"]):
            sid = c.structure_id(si, pi)
            files[UTI_DIR / f"structure_{sid}.uti.json"] = dump_json(structure_item(template, sid, piece))
            structures.append((f"structure_{sid}", piece["name"]))
        for kind in ("dish", "drink"):
            item = entry[kind]
            source = cooking_source(item["copies"])
            resref = signature_resref(entry, kind)
            uti, _ = signature_item(source["resref"], resref, item, place)
            files[UTI_DIR / f"{resref}.uti.json"] = dump_json(uti)
            foods.append((resref, item["name"]))
    files[PALETTE] = dump_json(update_palette(palette, structures, foods))
    files[STRUCTURE_ENUM] = replace_block(read_text(STRUCTURE_ENUM), STRUCTURE_BEGIN, STRUCTURE_END, structure_block(), STRUCTURE_ANCHOR)
    files[RECIPE_ENUM] = replace_block(read_text(RECIPE_ENUM), RECIPE_BEGIN, RECIPE_END, recipe_block(), RECIPE_ANCHOR)
    files[DECOR_RECIPES] = with_existing_parameters(DECOR_RECIPES, decor_recipes_cs())
    files[SIGNATURE_RECIPES] = with_existing_parameters(SIGNATURE_RECIPES, signature_recipes_cs())
    return files


def check_catalog():
    """Fails loudly on a catalog mistake before anything is written."""
    problems = []
    used = {}
    structure_names = set()
    for path in [STRUCTURE_ENUM]:
        structure_names.update(re.findall(r'\[Structure\("[^"]*",\s*"([^"]*)"', read_text(path)))
    own = {p["placeable"] for e in c.SETS for p in e["decor"]}
    for e in c.SETS:
        for p in e["decor"]:
            if not (UTP_DIR / f"{p['placeable']}.utp.json").exists():
                problems.append(f"{p['enum']}: placeable {p['placeable']} is not in the module")
            used.setdefault(p["placeable"], []).append(p["enum"])
        for kind in ("dish", "drink"):
            for resref, _ in e[kind]["components"]:
                if not (UTI_DIR / f"{resref}.uti.json").exists():
                    problems.append(f"{e[kind]['enum']}: component {resref} is not in the module")
            if len(signature_resref(e, kind)) > 16:
                problems.append(f"{signature_resref(e, kind)} is longer than 16 characters")
    for placeable, users in used.items():
        if len(users) > 1:
            problems.append(f"{placeable} is used by {users}")
    # A placeable a structure outside this content already uses is not new.
    others = set()
    text = read_text(STRUCTURE_ENUM)
    text = re.sub(re.escape(STRUCTURE_BEGIN) + r".*?" + re.escape(STRUCTURE_END), "", text, flags=re.S)
    for match in re.finditer(r'\[Structure\("(?:[^"\\]|\\.)*",\s*"([^"]*)"', text):
        others.add(match.group(1))
    for placeable in own & others:
        problems.append(f"{placeable} is already used by another structure")
    if problems:
        raise SystemExit("catalog problems:\n  " + "\n  ".join(problems))


def main():
    check_catalog()
    files = build()
    changed = []
    for path, text in files.items():
        current = read_text(path) if path.exists() else None
        if current != text:
            changed.append(path)
    if "--check" in sys.argv:
        for path in changed:
            print("out of date:", path.relative_to(ROOT))
        print("planet identity content current" if not changed else f"{len(changed)} files out of date")
        sys.exit(1 if changed else 0)
    for path in changed:
        path.write_bytes(files[path].replace("\n", "\r\n").encode("utf-8"))
    print(f"wrote {len(changed)} files ({len(files) - len(changed)} already current)")


if __name__ == "__main__":
    main()
