using System.Text;

namespace SWLOR.EngineSeamGenerator;

/// <summary>
/// Writes the frame shared by every generated part: the generated-code header, the using directives of the wrapper file
/// the part mirrors, and the namespace block. Copying the wrapper file's usings exactly keeps every type name resolving
/// the way it does in the wrapper, including per-file aliases such as two different `Alignment` types.
/// </summary>
internal static class PartWriter
{
    public const string Indent = "    ";

    public static StringBuilder Begin(WrapperSourceFile source, string @namespace, IEnumerable<string> extraNamespaceUsings)
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated>\n");
        text.Append("// Generated from ").Append(source.Path).Append(" by tools/Refactor/SWLOR.EngineSeamGenerator.\n");
        text.Append("// Do not edit this file. Change the wrapper, then run tools/Refactor/Apply-EngineSeam.ps1.\n");
        text.Append("// </auto-generated>\n");
        text.Append("#nullable enable\n");
        foreach (var directive in source.Usings)
        {
            text.Append(directive).Append('\n');
        }

        text.Append('\n');
        text.Append("namespace ").Append(@namespace).Append('\n');
        text.Append("{\n");
        foreach (var directive in extraNamespaceUsings)
        {
            text.Append(Indent).Append(directive).Append('\n');
        }

        return text;
    }

    public static void AppendDocs(StringBuilder text, WrapperMember member)
    {
        foreach (var line in member.DocLines)
        {
            text.Append(Indent).Append(Indent).Append(line).Append('\n');
        }
    }

    public static string End(StringBuilder text)
    {
        text.Append("}\n");
        return text.ToString();
    }
}
