namespace SWLOR.EngineSeamGenerator;

/// <summary>Emits the runtime that holds the engine implementation the static wrappers forward to.</summary>
internal static class RuntimeEmitter
{
    public static string Emit(SeamDefinition definition)
    {
        return Template
            .Replace("__NAMESPACE__", definition.Namespace)
            .Replace("__STATIC__", definition.StaticClassName)
            .Replace("__INTERFACE__", definition.InterfaceName)
            .Replace("__PASSTHROUGH__", definition.PassThroughName)
            .Replace("__RUNTIME__", definition.RuntimeName)
            .Replace("__FAKE__", definition.FakeName)
            .Replace("\r\n", "\n");
    }

    private const string Template = """
        // <auto-generated>
        // Generated by tools/Refactor/SWLOR.EngineSeamGenerator.
        // Do not edit this file. Run tools/Refactor/Apply-EngineSeam.ps1 instead.
        // </auto-generated>
        #nullable enable
        using System.Runtime.CompilerServices;

        namespace __NAMESPACE__
        {
            /// <summary>
            /// Holds the engine implementation that the static <see cref="__STATIC__"/> wrappers forward to.
            /// The default is <see cref="__PASSTHROUGH__"/>, which sends every call to the game engine exactly as the
            /// wrappers did before the seam existed. Tests swap it for a fake with <see cref="Override"/>.
            /// </summary>
            public static class __RUNTIME__
            {
                private static readonly __PASSTHROUGH__ Default = new();
                private static readonly AsyncLocal<OverrideScope?> Overridden = new();
                private static int _activeOverrides;

                /// <summary>
                /// The implementation the wrappers call. While no override exists anywhere this is one static field read
                /// and one comparison; it never allocates.
                /// </summary>
                public static __INTERFACE__ Current
                {
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    get
                    {
                        if (Volatile.Read(ref _activeOverrides) == 0)
                        {
                            return Default;
                        }

                        return FindOverride() ?? Default;
                    }
                }

                /// <summary>
                /// Test-only. Makes <paramref name="engine"/> the implementation for the current async flow until the
                /// returned scope is disposed, then restores the previous one. The override lives in an
                /// <see cref="AsyncLocal{T}"/>, so tests running in parallel do not see each other's fakes. A disposed
                /// scope stops applying everywhere, including in tasks that captured it, which then see the next live
                /// scope of their own flow or the default.
                /// </summary>
                public static IDisposable Override(__INTERFACE__ engine)
                {
                    ArgumentNullException.ThrowIfNull(engine);

                    var scope = new OverrideScope(engine, Overridden.Value);
                    Overridden.Value = scope;
                    Interlocked.Increment(ref _activeOverrides);
                    return scope;
                }

                private static __INTERFACE__? FindOverride()
                {
                    for (var scope = Overridden.Value; scope != null; scope = scope.Previous)
                    {
                        if (scope.IsActive)
                        {
                            return scope.Engine;
                        }
                    }

                    return null;
                }

                private sealed class OverrideScope(__INTERFACE__ engine, OverrideScope? previous) : IDisposable
                {
                    private int _disposed;

                    public __INTERFACE__ Engine { get; } = engine;

                    public OverrideScope? Previous { get; } = previous;

                    public bool IsActive => Volatile.Read(ref _disposed) == 0;

                    public void Dispose()
                    {
                        if (Interlocked.Exchange(ref _disposed, 1) != 0)
                        {
                            return;
                        }

                        // Only the flow that is still inside this scope steps back; a flow that merely inherited it, or
                        // that has since installed a scope of its own, keeps what it has (a disposed scope is skipped).
                        if (ReferenceEquals(Overridden.Value, this))
                        {
                            Overridden.Value = Previous;
                        }

                        Interlocked.Decrement(ref _activeOverrides);
                    }
                }
            }
        }
        """ + "\n";
}
