using System.Diagnostics;
using System.Text;
using SWLOR.Game.Server.Service.SlicingService;

if (args.Length != 1)
{
    Console.Error.WriteLine("Usage: SWLOR.SlicingBoardGenerator <SlicingBoardCatalog.Generated.cs> | --report (build with -c Release; Debug is several times slower)");
    return 1;
}

if (args[0] == "--report")
{
    ReportCompiledCatalog();
    return 0;
}

var outputPath = Path.GetFullPath(args[0]);
var parallelism = new ParallelOptions { MaxDegreeOfParallelism = Math.Max(1, Environment.ProcessorCount / 2) };
var source = new StringBuilder();
source.AppendLine("// <auto-generated />");
source.AppendLine("// Run: dotnet run -c Release --project tools/SWLOR.SlicingBoardGenerator -- SWLOR.Game.Server/Service/SlicingService/SlicingBoardCatalog.Generated.cs");
source.AppendLine("using System.Collections.Generic;");
source.AppendLine();
source.AppendLine("namespace SWLOR.Game.Server.Service.SlicingService");
source.AppendLine("{");
source.AppendLine("    public static partial class SlicingBoardCatalog");
source.AppendLine("    {");
source.AppendLine("        private static readonly IReadOnlyDictionary<int, string[]> _encodedBoards =");
source.AppendLine("            new Dictionary<int, string[]>");
source.AppendLine("            {");

for (var tier = 1; tier <= 5; tier++)
{
    var stopwatch = Stopwatch.StartNew();
    var boards = new SlicingBoard[SlicingBoardAuthoring.BoardsPerTier];
    // Each board depends only on its own seeds, so parallel generation stays deterministic.
    // Half the cores leaves room for other work on a shared machine.
    Parallel.For(1, boards.Length + 1, parallelism, boardNumber =>
        boards[boardNumber - 1] = SlicingBoardAuthoring.GenerateBoard(tier, boardNumber));

    // Every board number must show players a different starting layout.
    var layouts = new HashSet<string>();
    for (var index = 0; index < boards.Length; index++)
    {
        var variant = 0;
        while (!layouts.Add(Layout(boards[index])))
            boards[index] = SlicingBoardAuthoring.GenerateBoard(tier, index + 1, ++variant);
    }

    source.AppendLine($"                [{tier}] = new[]");
    source.AppendLine("                {");
    foreach (var board in boards)
        source.AppendLine($"                    \"{Encode(board)}\",");
    source.AppendLine("                },");

    var costs = boards.Select(board => board.SolutionActionCost).ToList();
    var routeLengths = boards.Select(board => board.Tiles.Count(tile => tile.SolutionIndex >= 0)).ToList();
    var swaps = boards.Select(board => board.SolutionSwaps.Count).ToList();
    Console.WriteLine(
        $"Tier {tier}: {boards.Length} boards in {stopwatch.Elapsed.TotalSeconds:0}s, " +
        $"solution cost {costs.Min()}-{costs.Max()} (avg {costs.Average():0.0}), " +
        $"route cells {routeLengths.Min()}-{routeLengths.Max()} (avg {routeLengths.Average():0.0}), " +
        $"solution swaps {swaps.Min()}-{swaps.Max()} (avg {swaps.Average():0.0}).");
}

source.AppendLine("            };");
source.AppendLine("    }");
source.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, source.ToString());
Console.WriteLine($"Generated {5 * SlicingBoardAuthoring.BoardsPerTier} slicing boards at {outputPath}.");
return 0;

// Difficulty metrics for the catalog compiled into SWLOR.Game.Server. "Routes" counts distinct
// cell paths a player can power within base trace, and within base trace plus the largest bonus
// the live rules allow for that tier (Slicing V and capped Lockpicking plus Perception).
static void ReportCompiledCatalog()
{
    var parallelism = new ParallelOptions { MaxDegreeOfParallelism = Math.Max(1, Environment.ProcessorCount / 2) };
    const int maximumSlicingRank = 5;
    const int routeCap = 50;
    for (var tier = 1; tier <= 5; tier++)
    {
        var maximumTraceBonus = Slicing.GetTraceBonus(
            maximumSlicingRank, tier, Slicing.StatPointsPerTrace * Slicing.MaxStatTraceBonus, 0);
        var boards = Enumerable.Range(1, Slicing.GetBoardCount(tier)).Select(number => Slicing.GetBoard(tier, number)).ToArray();
        var optimal = new int[boards.Length];
        var swapFree = new bool[boards.Length];
        var routes = new int[boards.Length];
        var bonusRoutes = new int?[boards.Length];
        Parallel.For(0, boards.Length, parallelism, index =>
        {
            var board = boards[index];
            optimal[index] = SlicingBoardSolver.Solve(board, board.SolutionActionCost + 1)!.Cost;
            swapFree[index] = SlicingBoardSolver.Solve(board, board.BaseTrace + 1, allowSwaps: false) != null;
            routes[index] = SlicingBoardSolver.CountRoutes(board, board.BaseTrace, routeCap);
            try
            {
                bonusRoutes[index] = SlicingBoardSolver.CountRoutes(board, board.BaseTrace + maximumTraceBonus, routeCap, nodeLimit: 2_000_000);
            }
            catch (SlicingBoardSolver.SearchLimitExceededException)
            {
                // Too many candidate paths to confirm within the search limit; reported separately.
                bonusRoutes[index] = null;
            }
        });

        var count = (double)boards.Length;
        var confirmedBonusRoutes = bonusRoutes.Where(value => value.HasValue).Select(value => value!.Value).ToList();
        var bonusSummary = confirmedBonusRoutes.Count == 0
            ? "not confirmed on any board"
            : $"median {confirmedBonusRoutes.Order().ElementAt(confirmedBonusRoutes.Count / 2)} " +
              $"avg {confirmedBonusRoutes.Average():0.0} over {confirmedBonusRoutes.Count} confirmed boards " +
              $"(capped at {routeCap}; {boards.Length - confirmedBonusRoutes.Count} exceeded the search limit)";
        Console.WriteLine(
            $"Tier {tier}: {boards.Length} boards, base trace avg {boards.Average(board => board.BaseTrace):0.0}, " +
            $"recorded cost avg {boards.Average(board => board.SolutionActionCost):0.0}, optimal avg {optimal.Average():0.0}, " +
            $"cheaper than recorded {boards.Where((board, index) => optimal[index] < board.SolutionActionCost).Count() / count:P0}, " +
            $"solvable without swaps {swapFree.Count(value => value) / count:P0}, " +
            $"routes in base trace avg {routes.Average():0.0} (single-route boards {routes.Count(value => value == 1) / count:P0}), " +
            $"routes with the maximum +{maximumTraceBonus} {bonusSummary}.");
    }
}

static string Layout(SlicingBoard board) =>
    string.Join(";", board.Tiles.Select(tile => $"{(int)tile.Type},{tile.Orientation}"));

static string Encode(SlicingBoard board)
{
    var tiles = string.Join(";", board.Tiles.Select(tile =>
        $"{(int)tile.Type},{tile.Orientation},{tile.SolutionIndex},{tile.RouteOrder},{tile.SolutionOrientation}"));
    var swaps = string.Join(";", board.SolutionSwaps.Select(swap =>
        $"{swap.FirstIndex},{swap.SecondIndex}"));
    return $"{board.Width},{board.Height}|{board.BaseTrace},{board.SolutionActionCost}|{tiles}|{swaps}";
}
