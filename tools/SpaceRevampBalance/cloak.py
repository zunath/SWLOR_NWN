CYCLE_SECONDS = 1.0       # the device draws capacitor every cycle while it is on
CAPACITOR = 2             # per cycle: 2 per second against a Small hull's 2.5-3.0 regeneration
FIT_SIZE = "Small"        # every Small role fits one; the only Medium role that does is the Blockade Runner
FIT_ROLES = ["Blockade Runner"]

# Cloak time: from the press until the ship disappears. The ship cannot use a module or ability from the press.
ENGAGE_SECONDS = 4.0
ROLE_ENGAGE_SECONDS = 2.0

# Speed while cloaking or cloaked, as a percent of the ship's speed (the Bible draft's -50%).
SPEED_PERCENT = 50
ROLE_SPEED_PERCENT = 65

# Interceptors, Bombers and Explorers: a faster cloak and a smaller speed penalty. Fighters and Blockade Runners get
# neither; the Blockade Runner's own edge is cargo.
ROLE_BONUS_ROLES = ["Interceptor", "Bomber", "Explorer"]
CARGO_ROLES = ["Blockade Runner"]

# Decloaking: firing stays locked this long after the ship becomes visible again (a cloak that never finished engaging
# locks nothing).
DECLOAK_LOCK_SECONDS = 5

# Reveal range: any ship within this many meters sees the cloaked ship; a better device is harder to see.
REVEAL_BASE_METERS = 10
REVEAL_RANKS_PER_METER = 9


def reveal_range(rank):
    """Meters at which another ship reveals a ship cloaked with a device of this rank (Mk I 10 m, Mk X 5 m)."""
    return REVEAL_BASE_METERS - rank // REVEAL_RANKS_PER_METER


# Espionage (W11n, plan section 4): the observing ship's best Espionage rank (its pilot's or its Sensors officer's)
# stretches the reveal range by 1% per rank, up to +50% at rank 50 (the Probe Launcher's scan bonus): Mk I 10 -> 15 m,
# Mk X and the Barracuda 5 -> 7.5 m. A percent of the device's range keeps a better device harder to see at every rank.
ESPIONAGE_REVEAL_PERCENT_PER_RANK = 1
ESPIONAGE_REVEAL_MAXIMUM_RANK = 50


def espionage_reveal_range(meters, espionage_rank):
    """Meters at which an observer with this Espionage rank reveals a cloak whose own reveal range is `meters`."""
    return meters * (1 + min(max(espionage_rank, 0), ESPIONAGE_REVEAL_MAXIMUM_RANK) * ESPIONAGE_REVEAL_PERCENT_PER_RANK / 100)


# A Sensor Sweep that finds a cloaked ship reveals it to the sweeper's party this long.
SWEEP_REVEAL_SECONDS = 10

# Hull signatures.
