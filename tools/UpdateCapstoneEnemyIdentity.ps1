function Get-LegacyProfileSignatureDisplayName([string]$profile, [bool]$isBeast, [string]$title) {
    $profileKey = Get-SignatureProfileKey $profile $isBeast
    $legacyProfileDisplayName = @{
        Beast = "Beast"
        CreaturePhysical = "Beast"
        Devices = "Tech"
        Force = "Force"
        Rifle = "Rifle"
        Staff = "Staff"
        Throwing = "Thrown"
        Vibroblade = "Blade"
    }

    if (!$legacyProfileDisplayName.Contains($profileKey)) {
        throw "Missing legacy signature profile display name for profile '$profileKey'."
    }

    $prefix = $legacyProfileDisplayName[$profileKey]
    if ($title.StartsWith("$prefix ", [StringComparison]::OrdinalIgnoreCase)) {
        return $title
    }

    return "$prefix $title"
}

