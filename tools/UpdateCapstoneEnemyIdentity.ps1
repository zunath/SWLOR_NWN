function Add-SignatureLegacyReferences(
    [System.Collections.Generic.List[string]]$legacyFeatNames,
    [System.Collections.Generic.List[string]]$legacyIconResrefs,
    [System.Collections.Generic.List[string]]$legacyTlkTexts,
    $line,
    [string]$profile,
    [string]$title,
    $stepData,
    [int]$step) {
    Add-UniqueString $legacyFeatNames "Capstone$($line.Perk)$($stepPascalLabels[$step])"
    Add-UniqueString $legacyIconResrefs (Get-LegacySignatureIconResref $line $step)
    Add-UniqueString $legacyIconResrefs (Get-LineSignatureIconResref $line $step)

    $titles = [System.Collections.Generic.List[string]]::new()
    Add-UniqueString $titles $title
    if ($signatureLegacyTitlesByTitle.ContainsKey($title)) {
        foreach ($legacyTitle in $signatureLegacyTitlesByTitle[$title]) {
            Add-UniqueString $titles $legacyTitle
        }
    }

    foreach ($legacyTitle in $titles) {
        $legacyDisplayName = Get-LegacyProfileSignatureDisplayName $profile $line.IsBeast $legacyTitle
        Add-UniqueString $legacyFeatNames (Get-LineSignatureFeatName $line $legacyTitle)
        Add-UniqueString $legacyFeatNames (Get-SignatureFeatName $legacyDisplayName)
        if ($legacyTitle -ne $title) {
            Add-UniqueString $legacyFeatNames (Get-SignatureFeatName $legacyTitle)
            Add-UniqueString $legacyIconResrefs (Get-SignatureIconResref $legacyTitle)
            Add-UniqueString $legacyTlkTexts $legacyTitle
            Add-UniqueString $legacyTlkTexts "$legacyTitle is a reusable level 50 enemy technique used by $($stepLabels[$step]) enemies. Deals $($stepData.DamageType) damage and applies $($stepData.Status -replace 'StatusEffect$', '') for $([int](6 + ($step * 2))) seconds."
        }
        Add-UniqueString $legacyIconResrefs (Get-LegacyProfileSignatureIconResref $profile $line.IsBeast $legacyTitle)
        Add-UniqueString $legacyTlkTexts "$($line.DisplayName) $legacyTitle"
        Add-UniqueString $legacyTlkTexts "$($line.DisplayName) trial technique used by the $($stepLabels[$step]) enemy. Deals $($stepData.DamageType) damage and applies $($stepData.Status -replace 'StatusEffect$', '') for $([int](6 + ($step * 2))) seconds."
        Add-UniqueString $legacyTlkTexts $legacyDisplayName
        Add-UniqueString $legacyTlkTexts "$legacyDisplayName is a reusable level 50 enemy technique used by $($stepLabels[$step]) enemies. Deals $($stepData.DamageType) damage and applies $($stepData.Status -replace 'StatusEffect$', '') for $([int](6 + ($step * 2))) seconds."
    }
}

