function Get-WorksheetInfo($archive, $parts, [string]$sheetName) {
    $workbookNs = New-Object Xml.XmlNamespaceManager($parts.Workbook.NameTable)
    $workbookNs.AddNamespace("d", "http://schemas.openxmlformats.org/spreadsheetml/2006/main")
    $workbookNs.AddNamespace("r", "http://schemas.openxmlformats.org/officeDocument/2006/relationships")
    $relationshipNs = New-Object Xml.XmlNamespaceManager($parts.Relationships.NameTable)
    $relationshipNs.AddNamespace("pr", "http://schemas.openxmlformats.org/package/2006/relationships")

    $sheet = $parts.Workbook.SelectSingleNode("//d:sheet[@name='$sheetName']", $workbookNs)
    if ($null -eq $sheet) {
        throw "Workbook sheet '$sheetName' was not found."
    }

    $relationshipId = $sheet.GetAttribute("id", "http://schemas.openxmlformats.org/officeDocument/2006/relationships")
    $relationship = $parts.Relationships.SelectSingleNode("//pr:Relationship[@Id='$relationshipId']", $relationshipNs)
    $path = "xl/" + $relationship.GetAttribute("Target").TrimStart("/")
    $doc = New-Object Xml.XmlDocument
    $doc.PreserveWhitespace = $true
    $stream = $archive.GetEntry($path).Open()
    try {
        $doc.Load($stream)
    }
    finally {
        $stream.Dispose()
    }

    return [pscustomobject]@{
        Path = $path
        Document = $doc
    }
}

function Get-Column([string]$cellRef) {
    return $cellRef -replace "\d", ""
}

function Get-CellText($cell, $worksheetNs, $sharedStrings) {
    if ($null -eq $cell) {
        return ""
    }

    $type = $cell.GetAttribute("t")
    $value = $cell.SelectSingleNode("d:v", $worksheetNs)
    $inline = $cell.SelectSingleNode("d:is", $worksheetNs)

    if ($type -eq "s" -and $null -ne $value) {
        return $sharedStrings[[int]$value.InnerText]
    }

    if ($type -eq "inlineStr" -and $null -ne $inline) {
        $text = ""
        foreach ($t in $inline.SelectNodes(".//d:t", $worksheetNs)) {
            $text += $t.InnerText
        }
        return $text
    }

    if ($null -ne $value) {
        return $value.InnerText
    }

    return ""
}

function Read-WorkbookTable($archive, $parts, [string]$sheetName) {
    $info = Get-WorksheetInfo $archive $parts $sheetName
    $doc = $info.Document
    $ns = New-Object Xml.XmlNamespaceManager($doc.NameTable)
    $ns.AddNamespace("d", "http://schemas.openxmlformats.org/spreadsheetml/2006/main")
    $headers = @{}
    $headerRow = $doc.SelectSingleNode("//d:sheetData/d:row[@r='1']", $ns)

    foreach ($cell in $headerRow.SelectNodes("d:c", $ns)) {
        $headers[(Get-Column $cell.GetAttribute("r"))] = Get-CellText $cell $ns $parts.SharedStrings
    }

    $rows = New-Object System.Collections.Generic.List[hashtable]
    foreach ($row in $doc.SelectNodes("//d:sheetData/d:row", $ns)) {
        if ($row.GetAttribute("r") -eq "1") {
            continue
        }

        $data = @{}
        foreach ($cell in $row.SelectNodes("d:c", $ns)) {
            $column = Get-Column $cell.GetAttribute("r")
            if ($headers.ContainsKey($column)) {
                $data[$headers[$column]] = Get-CellText $cell $ns $parts.SharedStrings
            }
        }

        if ($data.Count -gt 0 -and -not [string]::IsNullOrWhiteSpace([string]$data.Values[0])) {
            $rows.Add($data)
        }
    }

    return $rows
}

