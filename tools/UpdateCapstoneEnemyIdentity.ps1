function Get-SignatureIconResref([string]$title) {
    if (!$signatureIconTitleCodeByTitle.Contains($title)) {
        throw "Missing signature icon title code for '$title'."
    }

    $resref = "ife_$($signatureIconTitleCodeByTitle[$title])"
    if ($resref.Length -gt 16) {
        throw "Signature icon resref '$resref' exceeds NWN's 16 character limit."
    }

    return $resref
}

function Get-LineSignatureIconResref($line, [int]$step) {
    if (!$signatureIconCodeByLineCode.Contains($line.Code)) {
        throw "Missing signature icon code for line code '$($line.Code)'."
    }
    if (!$signatureIconTitleCodeByRole.Contains($line.Role)) {
        throw "Missing signature icon title code for role '$($line.Role)'."
    }

    return "ife_$($signatureIconCodeByLineCode[$line.Code])$($signatureIconTitleCodeByRole[$line.Role][$step])"
}

function Get-LegacySignatureIconResref($line, [int]$step) {
    if (!$legacySignatureIconCodeByLineCode.Contains($line.Code)) {
        throw "Missing legacy signature icon code for line code '$($line.Code)'."
    }

    return "ife_cq$($legacySignatureIconCodeByLineCode[$line.Code])$($stepSuffixes[$step])"
}

