function Write-TlkJsonFile([string]$path, $tlk) {
    $builder = [Text.StringBuilder]::new()
    [void]$builder.AppendLine('{')
    [void]$builder.AppendLine("  ""language"": $([int]$tlk.language),")
    [void]$builder.AppendLine('  "entries": [')

    $entries = @($tlk.entries | Sort-Object { [int]$_.id })
    for ($i = 0; $i -lt $entries.Count; $i++) {
        $entry = $entries[$i]
        [void]$builder.AppendLine('    {')
        [void]$builder.AppendLine("      ""id"": $([int]$entry.id),")
        [void]$builder.AppendLine("      ""text"": $(ConvertTo-TlkJsonString ([string]$entry.text))")
        if ($i -lt $entries.Count - 1) {
            [void]$builder.AppendLine('    },')
        }
        else {
            [void]$builder.AppendLine('    }')
        }
    }

    [void]$builder.AppendLine('  ]')
    [void]$builder.AppendLine('}')

    $utf8NoBom = [Text.UTF8Encoding]::new($false)
    [IO.File]::WriteAllText($path, $builder.ToString(), $utf8NoBom)
}

function Update-NPCSignatureFeatRows($abilities) {
    $tlk = [IO.File]::ReadAllText($tlkJsonPath, [Text.Encoding]::UTF8) | ConvertFrom-Json
    $legacyTlkTexts = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    foreach ($ability in $abilities) {
        foreach ($legacyText in @($ability.LegacyTlkTexts)) {
            if (![string]::IsNullOrWhiteSpace([string]$legacyText)) {
                [void]$legacyTlkTexts.Add([string]$legacyText)
            }
        }
    }

    if ($legacyTlkTexts.Count -gt 0) {
        foreach ($entry in $tlk.entries) {
            if ($legacyTlkTexts.Contains([string]$entry.text)) {
                $entry.text = ""
            }
        }
    }

    $byId = @{}
    $byText = @{}
    foreach ($entry in $tlk.entries) {
        $entryId = [int]$entry.id
        $byId[$entryId] = $entry
        $text = [string]$entry.text
        if (![string]::IsNullOrWhiteSpace($text) -and !$byText.ContainsKey($text)) {
            $byText[$text] = 16777216 + $entryId
        }
    }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.AddRange([IO.File]::ReadAllLines($feat2daPath))
    $headerIndex = Get-2DAHeaderIndex $lines.ToArray()
    $headers = $lines[$headerIndex].Trim() -split "\s+"
    $expectedTokens = $headers.Count + 1
    $rowLine = @{}
    $rowByLabel = @{}
    $maxRow = 0

    for ($i = $headerIndex + 1; $i -lt $lines.Count; $i++) {
        $tokens = ConvertTo-StringList $lines[$i]
        $rowNumber = Get-2DARowNumber $tokens
        if ($null -eq $rowNumber) {
            continue
        }

        $rowLine[$rowNumber] = $i
        if ($rowNumber -gt $maxRow) {
            $maxRow = $rowNumber
        }

        if ($tokens.Count -gt 1 -and $tokens[1] -ne "****") {
            $rowByLabel[$tokens[1]] = $rowNumber
        }
    }

    $template = (ConvertTo-StringList $lines[$rowLine[$signatureFeatStart - 1]])
    if ($template.Count -ne $expectedTokens) {
        throw "Unexpected feat.2da template width."
    }

    $enumSource = Get-Content -Path $featTypePath -Raw
    $enumInsertions = New-Object System.Collections.Generic.List[string]
    $abilityIndex = 0

    foreach ($ability in $abilities) {
        $rowNumber = $signatureFeatStart + $abilityIndex
        $abilityIndex++

        if (!$rowLine.ContainsKey($rowNumber)) {
            $rowLine[$rowNumber] = $lines.Count
            $lines.Add("")
        }

        foreach ($legacyFeatName in $ability.LegacyFeatNames) {
            $legacyPattern = "(?m)^\s*$([regex]::Escape($legacyFeatName))\s*=\s*\d+,\s*\r?\n?"
            $enumSource = [regex]::Replace($enumSource, $legacyPattern, "")
        }

        $currentPattern = "(?m)^\s*$([regex]::Escape($ability.FeatName))\s*=\s*\d+,\s*\r?\n?"
        $enumSource = [regex]::Replace($enumSource, $currentPattern, "")

        $tokens = [System.Collections.Generic.List[string]]::new()
        $tokens.AddRange([string[]]$template)
        $tokens[0] = [string]$rowNumber
        Set-2DATokenByHeader $tokens $headers "LABEL" $ability.FeatName
        Set-2DATokenByHeader $tokens $headers "FEAT" (Get-CustomTlkReference $tlk $byId $byText $ability.DisplayName)
        Set-2DATokenByHeader $tokens $headers "DESCRIPTION" (Get-CustomTlkReference $tlk $byId $byText $ability.Description)
        Set-2DATokenByHeader $tokens $headers "ICON" $ability.IconResref
        Set-2DATokenByHeader $tokens $headers "SPELLID" "****"
        Set-2DATokenByHeader $tokens $headers "HostileFeat" "1"
        Set-2DATokenByHeader $tokens $headers "MinLevel" "99"
        $lines[$rowLine[$rowNumber]] = Format-2DARow $tokens.ToArray()

        $enumInsertions.Add("        $($ability.FeatName) = $rowNumber,") | Out-Null
    }

    $generatedFeatEnd = $signatureFeatStart + $abilities.Count - 1
    for ($i = $headerIndex + 1; $i -lt $lines.Count; $i++) {
        $tokens = ConvertTo-StringList $lines[$i]
        $rowNumber = Get-2DARowNumber $tokens
        if ($null -eq $rowNumber) {
            continue
        }

        if ($rowNumber -gt $generatedFeatEnd -and $rowNumber -le $legacySignatureFeatEnd) {
            $lines[$i] = $null
        }
    }

    $lines = [System.Collections.Generic.List[string]]::new([string[]]@($lines | Where-Object { $null -ne $_ }))
    [IO.File]::WriteAllLines($feat2daPath, $lines)

    if ($enumInsertions.Count -gt 0) {
        $closingMatch = [regex]::Match($enumSource, "(?s)(\r?\n\s*}\s*\r?\n}\s*)$")
        if (!$closingMatch.Success) {
            throw "Could not locate FeatType enum closing brace."
        }

        $enumSource = $enumSource.Insert($closingMatch.Index, [Environment]::NewLine + ($enumInsertions -join [Environment]::NewLine))
        [IO.File]::WriteAllText($featTypePath, $enumSource)
    }

    $tlk.entries = @($tlk.entries | Sort-Object { [int]$_.id })
    Write-TlkJsonFile $tlkJsonPath $tlk

    return $generatedFeatEnd
}

