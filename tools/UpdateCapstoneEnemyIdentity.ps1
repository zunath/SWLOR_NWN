function Add-UniqueString([System.Collections.Generic.List[string]]$list, [string]$value) {
    if (![string]::IsNullOrWhiteSpace($value) -and !$list.Contains($value)) {
        $list.Add($value) | Out-Null
    }
}

function Get-NPCSignatureAbilities($lines) {
    $abilities = New-Object System.Collections.Generic.List[object]
    $abilitiesByKey = @{}

    foreach ($line in $lines) {
        for ($step = 0; $step -lt $stepSuffixes.Count; $step++) {
            $role = $line.Role
            $stepData = $signatureRoleSteps[$role][$step]
            $title = $signatureTitleByRole[$role][$step]
            $shape = Get-SignatureAbilityShape $step
            $isArea = -not [string]::IsNullOrWhiteSpace($shape)
            $profile = Get-SignatureProfileName $line
            $key = Get-SignatureAbilityKey $role $step
            $displayName = Get-SignatureDisplayName $title
            $featName = Get-SignatureFeatName $displayName
            $legacyFeatNames = [System.Collections.Generic.List[string]]::new()
            $legacyIconResrefs = [System.Collections.Generic.List[string]]::new()
            $legacyTlkTexts = [System.Collections.Generic.List[string]]::new()

            if ($abilitiesByKey.ContainsKey($key)) {
                $ability = $abilitiesByKey[$key]
                $legacyFeatNames = $ability.LegacyFeatNames
                $legacyIconResrefs = $ability.LegacyIconResrefs
                $legacyTlkTexts = $ability.LegacyTlkTexts
                Add-SignatureLegacyReferences $legacyFeatNames $legacyIconResrefs $legacyTlkTexts $line $profile $title $stepData $step
                continue
            }

            Add-SignatureLegacyReferences $legacyFeatNames $legacyIconResrefs $legacyTlkTexts $line $profile $title $stepData $step

            $statusDuration = [int](6 + ($step * 2))
            if ($stepData.Status -eq 'KnockdownStatusEffect' -and $statusDuration -gt 6) {
                $statusDuration = 6
            }

            $ability = [pscustomobject]@{
                Key = $key
                Role = $role
                ProfileKey = "CreaturePhysical"
                IsBeast = $false
                Step = $step
                StepSuffix = $stepSuffixes[$step]
                StepLabel = $stepLabels[$step]
                FeatName = $featName
                LegacyFeatNames = $legacyFeatNames
                LegacyTlkTexts = $legacyTlkTexts
                ClassName = "$($featName)AbilityDefinition"
                DisplayName = $displayName
                Description = "$displayName is a reusable level 50 enemy technique used by $($stepLabels[$step]) enemies. Deals $($stepData.DamageType) damage and applies $($stepData.Status -replace 'StatusEffect$', '') for $statusDuration seconds."
                IconResref = Get-SignatureIconResref $title
                LegacyIconResrefs = $legacyIconResrefs
                SemanticCategory = $stepData.Category
                BuilderKind = if ($isArea) { "Area" } else { "SingleTarget" }
                Shape = $shape
                LengthOrRadius = Get-SignatureRange $role $step
                Width = Get-SignatureWidth $step
                CenterOnActivator = $step -eq 2
                MaxRange = if ($isArea) { if ($step -eq 2) { 0.0 } else { Get-SignatureRange $role $step } } else { Get-SignatureRange $role $step }
                Profile = "CreaturePhysical"
                Animation = $stepData.Animation
                ActivationDelay = [decimal](0.8 + ($step * 0.15))
                RecastDelay = [decimal](22 + ($step * 4))
                Stamina = 5 + $step
                BaseDamage = Get-SignatureBaseDamage $role $step $false
                Duration = $statusDuration
                StatusEffect = $stepData.Status
                DamageType = $stepData.DamageType
                Resistance = $stepData.Resistance
                TargetVfx = $stepData.TargetVfx
                AreaVfx = $stepData.AreaVfx
            }

            $abilitiesByKey[$key] = $ability
            $abilities.Add($ability)
        }
    }

    return $abilities
}

function Format-CSharpFloat([decimal]$value) {
    return ([string]::Format($culture, "{0:0.0}", $value)) + "f"
}

function Write-NPCSignatureAbilityDefinitions($abilities) {
    New-Item -ItemType Directory -Path $abilityDefinitionPath -Force | Out-Null

    $expectedFiles = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($ability in $abilities) {
        $fileName = "$($ability.ClassName).cs"
        [void]$expectedFiles.Add($fileName)
        $path = Join-Path $abilityDefinitionPath $fileName
        $activationDelay = Format-CSharpFloat $ability.ActivationDelay
        $recastDelay = Format-CSharpFloat $ability.RecastDelay
        $maxRange = Format-CSharpFloat $ability.MaxRange
        $lengthOrRadius = Format-CSharpFloat $ability.LengthOrRadius
        $width = Format-CSharpFloat $ability.Width
        $centerOnActivator = if ($ability.CenterOnActivator) { "true" } else { "false" }

        if ($ability.BuilderKind -eq "Area") {
            $builderCall = @"
            NPCSignatureAbility.BuildArea(
                _builder,
                FeatType.$($ability.FeatName),
                "$($ability.DisplayName)",
                Animation.$($ability.Animation),
                InnateAbilityProfile.$($ability.Profile),
                $activationDelay,
                $recastDelay,
                $($ability.Stamina),
                $($ability.BaseDamage),
                $($ability.Duration),
                typeof($($ability.StatusEffect)),
                CombatImpactAreaShape.$($ability.Shape),
                $lengthOrRadius,
                $width,
                CombatDamageType.$($ability.DamageType),
                ResistanceType.$($ability.Resistance),
                VisualEffect.$($ability.TargetVfx),
                VisualEffect.$($ability.AreaVfx),
                maxRange: $maxRange,
                centerOnActivator: $centerOnActivator);
"@
        }
        else {
            $builderCall = @"
            NPCSignatureAbility.BuildSingleTarget(
                _builder,
                FeatType.$($ability.FeatName),
                "$($ability.DisplayName)",
                Animation.$($ability.Animation),
                InnateAbilityProfile.$($ability.Profile),
                $activationDelay,
                $recastDelay,
                $($ability.Stamina),
                $($ability.BaseDamage),
                $($ability.Duration),
                typeof($($ability.StatusEffect)),
                CombatDamageType.$($ability.DamageType),
                ResistanceType.$($ability.Resistance),
                VisualEffect.$($ability.TargetVfx),
                maxRange: $maxRange);
"@
        }

        $content = @"
using System.Collections.Generic;
using SWLOR.Game.Server.Service.AbilityService;
using SWLOR.Game.Server.Service.CombatService;
using SWLOR.NWN.API.NWScript.Enum;
using SWLOR.NWN.API.NWScript.Enum.VisualEffect;

namespace SWLOR.Game.Server.Feature.AbilityDefinition.NPC
{
$generatedAbilityDefinitionMarker

    public class $($ability.ClassName) : IAbilityListDefinition
    {
        private readonly AbilityBuilder _builder = new AbilityBuilder();

        public Dictionary<FeatType, AbilityDetail> BuildAbilities()
        {
$builderCall

            return _builder.Build();
        }
    }
}
"@

        [IO.File]::WriteAllText($path, $content.Replace("`r`n", "`n") + [Environment]::NewLine)
    }

    foreach ($file in Get-ChildItem -Path $abilityDefinitionPath -Filter "*AbilityDefinition.cs" -File) {
        if ($expectedFiles.Contains($file.Name)) {
            continue
        }

        $source = Get-Content -Path $file.FullName -Raw
        if ($source.Contains($generatedAbilityDefinitionMarker)) {
            Remove-Item -LiteralPath $file.FullName
        }
    }

    if (Test-Path -LiteralPath $legacyAbilityDefinitionPath) {
        Remove-Item -LiteralPath $legacyAbilityDefinitionPath -Recurse
    }
}

