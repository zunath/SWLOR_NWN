function Get-2DAHeaderIndex([string[]]$lines) {
    for ($i = 1; $i -lt $lines.Count; $i++) {
        if (![string]::IsNullOrWhiteSpace($lines[$i])) {
            return $i
        }
    }

    throw "Could not locate 2DA header line."
}

function Get-2DARowNumber([System.Collections.Generic.IList[string]]$tokens) {
    $rowNumber = 0
    if ($tokens.Count -eq 0 -or ![int]::TryParse($tokens[0], [ref]$rowNumber)) {
        return $null
    }

    return $rowNumber
}

function Set-2DATokenByHeader(
    [System.Collections.Generic.IList[string]]$tokens,
    [string[]]$headers,
    [string]$header,
    [string]$value) {
    $index = [array]::IndexOf($headers, $header)
    if ($index -lt 0) {
        throw "Could not find 2DA column '$header'."
    }

    $tokens[$index + 1] = $value
}

function Format-2DARow([string[]]$tokens) {
    $widths = @(
        7, 49, 11, 14, 19, 17, 9, 9, 9, 9, 9, 9, 13, 14, 14, 15, 15, 19,
        11, 8, 10, 12, 10, 13, 13, 13, 13, 13, 13, 13, 11, 18, 12, 20, 49,
        18, 14, 11, 16, 11, 13, 13, 12
    )

    $parts = for ($i = 0; $i -lt $tokens.Count; $i++) {
        $width = if ($i -lt $widths.Count) { $widths[$i] } else { 8 }
        $tokens[$i].PadRight($width)
    }

    return ($parts -join "").TrimEnd()
}

function Get-CustomTlkReference($tlk, $byId, $byText, [string]$text) {
    $trimmed = $text.Trim()
    if ([string]::IsNullOrWhiteSpace($trimmed)) {
        return "****"
    }

    if ($byText.ContainsKey($trimmed)) {
        return [string]$byText[$trimmed]
    }

    $entry = @($tlk.entries | Sort-Object { [int]$_.id } | Where-Object { [string]::IsNullOrWhiteSpace([string]$_.text) } | Select-Object -First 1)
    if ($entry.Count -gt 0) {
        $entryId = [int]$entry[0].id
        $entry[0].text = $trimmed
    }
    else {
        $usedIds = [System.Collections.Generic.HashSet[int]]::new()
        foreach ($existing in $tlk.entries) {
            [void]$usedIds.Add([int]$existing.id)
        }

        $maxId = if ($usedIds.Count -gt 0) { ($usedIds | Measure-Object -Maximum).Maximum } else { 0 }
        $entryId = $null
        for ($candidate = 0; $candidate -lt $maxId; $candidate++) {
            if (!$usedIds.Contains($candidate)) {
                $entryId = $candidate
                break
            }
        }

        if ($null -eq $entryId) {
            $entryId = $maxId + 1
        }

        $newEntry = [pscustomobject][ordered]@{
            id = [int]$entryId
            text = $trimmed
        }
        $tlk.entries += $newEntry
        $byId[[int]$entryId] = $newEntry
    }

    $strRef = 16777216 + [int]$entryId
    $byText[$trimmed] = $strRef
    return [string]$strRef
}

