function Convert-ToDecimal([string]$value) {
    if ([string]::IsNullOrWhiteSpace($value)) {
        return [decimal]0
    }

    return [decimal]::Parse($value, $culture)
}

function Convert-ToInt([decimal]$value) {
    return [int][Math]::Round($value, 0, [MidpointRounding]::AwayFromZero)
}

function Clamp-Int([int]$value, [int]$minimum, [int]$maximum) {
    return [Math]::Min($maximum, [Math]::Max($minimum, $value))
}

function Encode-Resistance([int]$value) {
    if ($value -lt 0) {
        return 100 + [Math]::Abs($value)
    }

    return $value
}

function Get-FeatMap {
    $source = Get-Content -Path $featTypePath -Raw
    $map = @{}
    foreach ($match in [regex]::Matches($source, "(?m)^\s*(?<name>[A-Za-z0-9_]+)\s*=\s*(?<value>\d+),")) {
        $map[$match.Groups["name"].Value] = [int]$match.Groups["value"].Value
    }

    return $map
}

function Get-CapstoneLines {
    $source = Get-Content -Path $capstoneSourcePath -Raw
    $areaByVariable = @{}
    foreach ($match in [regex]::Matches($source, "public static readonly CapstoneQuestAreaGroup\s+(?<variable>\w+)\s*=\s*new\(""(?<id>[^""]+)"",\s*""(?<name>[^""]+)""")) {
        $areaByVariable[$match.Groups["variable"].Value] = $match.Groups["name"].Value
    }

    $codeByLineId = @{}
    foreach ($match in [regex]::Matches($source, "\[""(?<id>[^""]+)""\]\s*=\s*new\(""[^""]+"",\s*""cq_(?<code>[^""]+)""\)")) {
        $codeByLineId[$match.Groups["id"].Value] = $match.Groups["code"].Value
    }

    $lines = New-Object System.Collections.Generic.List[object]
    $linePattern = "(?<kind>PlayerLine|BeastLine)\(""(?<id>[^""]+)"",\s*""(?<display>[^""]+)"",\s*PerkType\.(?<perk>\w+),\s*(?:(?:SkillType\.(?<skill>\w+))|(?:BeastRoleType\.(?<beastRole>\w+))),\s*AchievementType\.\w+,\s*(?<area>\w+),"
    $index = 0
    foreach ($match in [regex]::Matches($source, $linePattern)) {
        $id = $match.Groups["id"].Value
        $isBeast = $match.Groups["kind"].Value -eq "BeastLine"
        $skill = if ($match.Groups["skill"].Success) { $match.Groups["skill"].Value } else { $null }
        $beastRole = if ($match.Groups["beastRole"].Success) { $match.Groups["beastRole"].Value } else { $null }
        $role = $lineRoles[$id]
        $creatureType = if ($isBeast) {
            "Beast"
        }
        elseif ($skill -in @("Lightsaber", "Saberstaff", "Force")) {
            "Force User"
        }
        else {
            "Humanoid"
        }

        $lines.Add([pscustomobject]@{
            Index = $index
            Id = $id
            Perk = $match.Groups["perk"].Value
            Code = $codeByLineId[$id]
            DisplayName = $match.Groups["display"].Value
            AreaName = $areaByVariable[$match.Groups["area"].Value]
            Role = $role
            CreatureType = $creatureType
            IsBeast = $isBeast
            Skill = $skill
            BeastRole = $beastRole
        })
        $index++
    }

    return $lines
}

function Get-StepModifier($role, [int]$step, [int]$lineIndex) {
    if ($step -eq 0) {
        return "None"
    }

    if ($step -eq 1) {
        switch ($role) {
            "Tank" { return "High Durability" }
            "Ranged" { return "High Damage" }
            "Force" { return "High Resistance" }
            "Controller" { return "Low Resource" }
            "Support" { return "High Resistance" }
            "Swarm" { return "Hard to Hit" }
            default { return "High Damage" }
        }
    }

    if ($step -eq 2) {
        switch ($role) {
            "Tank" { return "High Durability" }
            "Ranged" { return "Hard to Hit" }
            "Force" { return "High Resistance" }
            "Controller" { return "Low Resource" }
            "Support" { return "High Resistance" }
            "Swarm" { return "Hard to Hit" }
            default { return "High Damage" }
        }
    }

    if ($step -eq 3) {
        $options = @("None", "High Damage", "Hard to Hit", "Low Resource")
        return $options[($lineIndex + $step) % $options.Count]
    }

    switch ($role) {
        "Tank" { return "High Durability" }
        "Ranged" { return "High Damage" }
        "Force" { return "High Resistance" }
        "Controller" { return "Hard to Hit" }
        "Support" { return "High Resistance" }
        "Swarm" { return "Glass Cannon" }
        default { return "High Damage" }
    }
}

function Get-RotatedPackage($line, [int]$step, [int]$count, $usedPackages) {
    $poolGroup = if ($line.IsBeast) { "Beast" } else { "Humanoid" }
    $pool = @($roleAbilityPools[$poolGroup][$line.Role])
    $global = if ($line.IsBeast) { $globalBeastAbilities } else { $globalHumanoidAbilities }
    $attempt = 0

    while ($attempt -lt 80) {
        $selected = New-Object System.Collections.Generic.List[string]
        $start = ($line.Index * 3 + $step * 2 + $attempt) % $pool.Count
        $roleTake = [Math]::Min($count - 1, 2 + ($step % 2))

        for ($i = 0; $i -lt $pool.Count -and $selected.Count -lt $roleTake; $i++) {
            $candidate = $pool[($start + $i) % $pool.Count]
            if (-not $selected.Contains($candidate)) {
                $selected.Add($candidate)
            }
        }

        $globalStart = ($line.Index * 7 + $step * 5 + $attempt) % $global.Count
        for ($i = 0; $i -lt $global.Count -and $selected.Count -lt $count; $i++) {
            $candidate = $global[($globalStart + $i) % $global.Count]
            if (-not $selected.Contains($candidate)) {
                $selected.Add($candidate)
            }
        }

        $signature = $global[($line.Index + ($step * 11) + ($attempt * 3)) % $global.Count]
        if (-not $selected.Contains($signature)) {
            if ($selected.Count -lt $count) {
                $selected.Add($signature)
            }
            else {
                $selected[$selected.Count - 1] = $signature
            }
        }

        $key = (@($selected) | Sort-Object) -join "|"
        if (-not $usedPackages.ContainsKey($key)) {
            $usedPackages[$key] = $true
            return @($selected)
        }

        $attempt++
    }

    throw "Unable to create unique ability package for $($line.Id) step $step."
}

function Get-SignatureProfileName($line) {
    if ($line.IsBeast) {
        if ($line.Role -eq "Force") {
            return "Force"
        }

        return "CreaturePhysical"
    }

    if ($line.Skill -in @("Devices", "FirstAid", "Leadership")) {
        return "Devices"
    }

    if ($line.Skill -eq "Force") {
        return "Force"
    }

    if ($line.Skill -in @("Rifle", "Pistol")) {
        return "Rifle"
    }

    if ($line.Skill -eq "Throwing") {
        return "Throwing"
    }

    if ($line.Skill -eq "Staff") {
        return "Staff"
    }

    return "Vibroblade"
}

function Get-SignatureAbilityShape([int]$step) {
    switch ($step) {
        1 { return "Cone" }
        2 { return "Sphere" }
        4 { return "Line" }
        default { return "" }
    }
}

function Get-SignatureRange([string]$role, [int]$step) {
    if ($step -in @(1, 2, 4)) {
        switch ($step) {
            1 { return 5.0 }
            2 { return 5.5 }
            4 { return 8.0 }
        }
    }

    if ($role -in @("Ranged", "Force", "Controller", "Support")) {
        return 12.0
    }

    return 3.0
}

function Get-SignatureWidth([int]$step) {
    switch ($step) {
        1 { return 5.0 }
        4 { return 2.5 }
        default { return 0.0 }
    }
}

function Get-SignatureBaseDamage([string]$role, [int]$step, [bool]$isBeast) {
    $base = switch ($role) {
        "Tank" { 17 }
        "Melee" { 20 }
        "Ranged" { 18 }
        "Force" { 18 }
        "Controller" { 15 }
        "Support" { 16 }
        "Swarm" { 19 }
        default { 17 }
    }

    $stepBonus = @(0, 4, 8, 6, 12)[$step]
    return $base + $stepBonus
}

